// Included from main.cpp immediately before runRestoreFlow(), so every UI
// helper (spr, fSet/fEnd, uiAsk/uiCard/uiPanel, buttons, camera + qrScanOnce)
// is already declared. Nothing here is a header in the usual sense — it is a
// slice of main.cpp kept in its own file so the feature can be read in one
// place.
//
// What the passphrase IS on this device (rulings of 23 Sep 2026):
//   * accepted at RESTORE for interop with words+passphrase wallets
//     (Sparrow / Coldcard users), and offered at CREATE as an option AFTER the
//     word-verify quiz. The derived seed is sealed in the SE; the passphrase is
//     consumed and never stored, so day-to-day use never asks for it.
//   * entry by TYPING on the four buttons (entered twice) or by SCANNING a QR
//     made on favillakey.io/verify/passphrase (reviewed, not re-entered).
//   * ASCII printable only, no whitespace stripping (a trailing space is drawn
//     so the owner can see it), 100-character cap.
//   * a mandatory wallet-fingerprint screen after derivation on both paths.
//
// Everything is blocking + synchronous, like the rest of onboarding: these
// screens run before the device has a network, so nothing is starved.

