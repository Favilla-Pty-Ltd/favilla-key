// ── The reel ────────────────────────────────────────────────────────────────
// Reel picker (25 Sep 2026 redesign). Four character SETS - abc / ABC / 123 /
// symbols - shown as tabs above the reel; SPACE and DONE sit at the start of
// every set so they are always one scroll away. SCROLL moves the reel, a TAP
// on ENTER adds the centred item, a HOLD on ENTER (0.5 s) switches to the next
// set, BACK deletes (or leaves on an empty box). The centre well widens for
// SPACE/DONE so the word fits, and neighbours give way to it.
#define PP_SETS 4
static const char* PP_TAB[PP_SETS] = { "abc", "ABC", "123", "#$%" };
static int ppSetBuild(int set, char* reel){
  int n=0;
  reel[n++]=0;         // DONE  (sentinel)
  reel[n++]=' ';       // SPACE
  if(set==0)      for(char c='a';c<='z';c++) reel[n++]=c;
  else if(set==1) for(char c='A';c<='Z';c++) reel[n++]=c;
  else if(set==2) for(char c='0';c<='9';c++) reel[n++]=c;
  else for(int c=0x21;c<=0x7E;c++){
    if((c>='a'&&c<='z')||(c>='A'&&c<='Z')||(c>='0'&&c<='9')) continue;
    reel[n++]=(char)c;
  }
  return n;
}
static bool ppIsWord(const char* reel, int idx){ return reel[idx]==0 || reel[idx]==' '; }
static const char* ppWord(const char* reel, int idx){ return reel[idx]==0 ? "DONE" : "SPACE"; }

// Draw a string centred on (cx, cy) using the font's own box - both axes.
static void ppCentre(const char* t, int cx, int cy){
  spr.setTextDatum(MC_DATUM); spr.drawString(t, cx, cy); spr.setTextDatum(TL_DATUM);
}
// Reel geometry: cells on a row centred at PP_REEL_Y, 34 px apart; the
// selected cell is a raised 40x52 (74 wide for a word) with a drop shadow.
#define PP_REEL_Y 176
static void ppDrawReelItem(const char* reel, int idx, int cx, int k){
  bool sel = (k == 0);
  if(ppIsWord(reel, idx)){
    uint16_t col = (reel[idx]==0) ? C_EB_BRASS : C_EB_BRASS;
    if(sel){ fSet(F_HEAD); spr.setTextColor(col); ppCentre(ppWord(reel, idx), cx, PP_REEL_Y); fEnd(); }
    else if(reel[idx]==0) spr.fillCircle(cx, PP_REEL_Y, 3, C_EB_BRASS);
    else spr.drawRect(cx-4, PP_REEL_Y-4, 8, 8, C_DIM);
    return;
  }
  char one[2]={reel[idx],0};
  if(sel){ fSet(F_TITLE); spr.setTextColor(C_EB_BRASS); ppCentre(one, cx, PP_REEL_Y); fEnd(); }
  else   { fSet(F_MONO);  spr.setTextColor(abs(k)==1 ? C_TEXT2 : C_DIM); ppCentre(one, cx, PP_REEL_Y); fEnd(); }
}
static void ppDrawReel(const char* reel, int n, int idx, int set){
  // Tabs as pills: the active set filled with an amber outline.
  fSet(F_HEAD_SM);
  for(int t=0;t<PP_SETS;t++){
    int x0 = 16 + t*54; bool act = (t==set);
    if(act) spr.fillRoundRect(x0, 110, 48, 18, 9, C_PANEL2);
    spr.drawRoundRect(x0, 110, 48, 18, 9, act ? C_EB_BRASS : C_BORDER2);
    spr.setTextColor(act ? C_EB_BRASS : C_DIM); ppCentre(PP_TAB[t], x0 + 24, 119);
  }
  fEnd();
  // Selected cell: shadow, panel, outline.
  bool word = ppIsWord(reel, idx);
  int ww = word ? 74 : 40, hh = 52;
  uint16_t oc = (word && reel[idx]==0) ? C_EB_BRASS : C_EB_BRASS;
  spr.fillRoundRect(120-ww/2+2, PP_REEL_Y-hh/2+3, ww, hh, 10, 0x0000);
  spr.fillRoundRect(120-ww/2,   PP_REEL_Y-hh/2,   ww, hh, 10, C_PANEL2);
  spr.drawRoundRect(120-ww/2,   PP_REEL_Y-hh/2,   ww, hh, 10, oc);
  spr.drawRoundRect(120-ww/2+1, PP_REEL_Y-hh/2+1, ww-2, hh-2, 9, oc);
  // Neighbours: 34 px pitch from the cell edge outward.
  for(int k=-3;k<=3;k++){
    if(k==0) continue;
    int j=(idx+k+n)%n;
    int sign=(k<0)?-1:1;
    int cx=120 + sign*(ww/2 + 17) + sign*(abs(k)-1)*34;
    if(cx < 10 || cx > 230) continue;
    ppDrawReelItem(reel, j, cx, k);
  }
  ppDrawReelItem(reel, idx, 120, 0);
  fSet(F_SMALL); spr.setTextColor(C_VDIM); ppCentre("hold ENTER to switch set", 120, 224); fEnd();
}

