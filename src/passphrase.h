// ── Validation ──────────────────────────────────────────────────────────────
// Returns nullptr when the passphrase is acceptable, else a short reason for
// the screen. Printable ASCII 0x20..0x7E only (space allowed anywhere — never
// stripped), 1..PP_MAX characters.
static const char* ppValidate(const char* s, size_t len){
  if(len==0)      return "Nothing to use";
  if(len>PP_MAX)  return "Over 100 characters";
  for(size_t i=0;i<len;i++){
    unsigned char c=(unsigned char)s[i];
    if(c<0x20 || c>0x7E) return "Not ASCII - plain characters only";
  }
  return nullptr;
}

// ── Master fingerprint from a 64-byte seed ──────────────────────────────────
// HASH160(compressed master pubkey)[0..4], the number Sparrow / Coldcard show.
static bool ppMasterFingerprint(const uint8_t seed[64], uint8_t fp[4]){
  bip32_xprv master;
  if(!bip32_master_from_seed(seed, 64, &master)) return false;
  uint8_t pub[33];
  bool ok = bip32_priv_to_pub_compressed(master.key, pub);
  if(ok){ uint8_t h[20]; hash160(pub, 33, h); memcpy(fp, h, 4); mbedtls_platform_zeroize(h, 20); }
  mbedtls_platform_zeroize(&master, sizeof(master));
  mbedtls_platform_zeroize(pub, sizeof(pub));
  return ok;
}
static void ppFpHex(const uint8_t fp[4], char out[9]){
  snprintf(out, 9, "%02x%02x%02x%02x", fp[0], fp[1], fp[2], fp[3]);
}

// ── Text box: the passphrase in the clear, on a monospace grid ──────────────
// 32 columns of 7 px (JetBrains Mono 12) from x=8, four rows of 16 px, so the
// full 100-character cap fits on screen. Drawn character by character so a
// SPACE gets its own mark (a dim 3x3 block at the baseline) — that is the only
// way a trailing space can be seen, and a passphrase with an invisible extra
// character is a lost wallet. `cursor` appends the amber insertion mark.
#define PP_COLS 32
#define PP_ROWS 4
static void ppDrawText(const char* s, int len, int x0, int y0, bool cursor){
  fSet(F_MONO);
  for(int i=0;i<len && i<PP_COLS*PP_ROWS;i++){
    int col=i%PP_COLS, row=i/PP_COLS;
    int x=x0+col*7, y=y0+row*16;
    if(s[i]==' '){
      spr.fillRect(x+2, y+9, 3, 3, C_DIM);
    } else {
      char one[2]={s[i],0};
      spr.setTextColor(C_FG); spr.drawString(one, x, y);
    }
  }
  fEnd();
  if(cursor && len<PP_COLS*PP_ROWS){
    int col=len%PP_COLS, row=len/PP_COLS;
    spr.fillRect(x0+col*7, y0+row*16+13, 6, 2, C_EB_BRASS);
  }
}
