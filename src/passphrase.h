// when DONE is chosen with at least one character. Returns false when the
// owner backs out (BACK with nothing entered). The reel position and set are
// remembered across the two passes.
static int g_ppReelPos = 2;   // first letter of the set (after DONE, SPACE)
static int g_ppReelSet = 0;
static bool ppPicker(const char* title, uint16_t titleCol, char* out, int* lenOut){
  char reel[48]; int set=g_ppReelSet; int n=ppSetBuild(set, reel);
  int len=0; out[0]=0;
  int idx=g_ppReelPos; if(idx>=n) idx=2;

  delay(200);
  btn1.poll(); btn2.poll(); btn3.poll(); btn4.poll();
  btn1.resetHold(); btn2.resetHold(); btn3.resetHold(); btn4.resetHold();
  clearButtonPending();

  bool redraw=true;
  while(true){
    if(redraw){
      spr.fillSprite(C_BG);
      fSet(F_HEAD_SM); spr.setTextColor(titleCol); spr.drawString(title, 8, 8); fEnd();
      ppDrawCount(len);
      ppDrawPanel(out, len, true);
      ppDrawReel(reel, n, idx, set);
      dispPush();
      redraw=false;
    }
    btn1.poll(); btn2.poll(); btn3.poll(); btn4.poll();
    float hDown=btn1.holdProgress(450);
    float hUp  =btn3.holdProgress(450);
    if(btn1.isPressed() || hDown>=1.0f){ idx=(idx+1)%n; redraw=true; delay(hDown>=1.0f ? 45 : 110); continue; }
    if(btn3.isPressed() || hUp>=1.0f){ idx=(idx+n-1)%n; redraw=true; delay(hUp>=1.0f ? 45 : 110); continue; }
    // ENTER: the press edge fires isPressed(); decide tap vs hold by watching
    // the release. Released inside 500 ms = tap (add the item). Still down at
    // 500 ms = hold (next set), then wait for the release so it can't repeat.
    if(btn2.isPressed()){
      unsigned long t0=millis(); bool held=false;
      while(btn2.stable==LOW){
        btn2.poll(); esp_task_wdt_reset(); delay(5);
        if(millis()-t0 >= 500){ held=true; break; }
      }
      if(held){
        set=(set+1)%PP_SETS; n=ppSetBuild(set, reel); idx=2;
        buzzerClick();
        while(btn2.stable==LOW){ btn2.poll(); esp_task_wdt_reset(); delay(5); }
        btn2.disarm(); btn2.resetHold();
        redraw=true; continue;
      }
      if(reel[idx]==0){                     // DONE
        clearButtonPending();
        if(len==0) return false;
        g_ppReelPos=idx; g_ppReelSet=set; *lenOut=len; out[len]=0;
        buzzerOK();
        return true;
      }
      if(len<PP_MAX){ out[len++]=reel[idx]; out[len]=0; }
      else buzzerFail();
      redraw=true; delay(60); continue;
    }
    if(btn4.isPressed()){
      if(len>0){ out[--len]=0; redraw=true; delay(110); continue; }
      clearButtonPending();
      g_ppReelPos=idx; g_ppReelSet=set;
      mbedtls_platform_zeroize(out, PP_MAX+1);
      return false;
    }
    esp_task_wdt_reset();
    delay(10);
  }
}

