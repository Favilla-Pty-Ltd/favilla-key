// The full onboarding step: mode, notices, entry. Returns the mode or -1
// (BACK on the mode screen: at restore "abandon", at create "none"). For
// PP_MODE_BAKED out holds the passphrase. For PP_MODE_SESSION out holds it
// only if the owner typed it as a rehearsal (*rehearsed = true); nothing is
// ever sealed from it in that mode.
static int ppCollectMode(char* out, size_t cap, bool restoreMode, bool* rehearsed){
  *rehearsed=false; out[0]=0;
  while(true){
    int mode = ppModeChoice(restoreMode);
    if(mode<0) return -1;
    if(mode==PP_MODE_NONE) return PP_MODE_NONE;
    if(!restoreMode){
      if(!ppNotice("Read this first",
                   "Your words alone will NOT",
                   "recover your funds.",
                   "You must also remember the",
                   "passphrase, exactly. Forever.",
                   nullptr, "HOLD ENTER TO CONFIRM", true)) continue;
    }
    if(mode==PP_MODE_SESSION){
      // 29 Oct 2026: full sentences (the fragments read like notes).
      // 29 Oct 2026: an explanation, not a warning, so brass. Says what
      // happens and what switching later costs.
      *rehearsed = (ppCheckNow(out, cap) == 1);   // 23 Nov 2026: one screen (was a notice + TYPE/SCAN/SKIP)
      return PP_MODE_SESSION;
    }
    int e = ppEntryMethod(out, cap, false);
    if(e<0) continue;
    return PP_MODE_BAKED;
  }
}

