// ── CIPHER AUDIO — non-blocking piezo sequencer ──────────────────────────────
// buzzerTone() blocks with delay() — unusable mid-gameplay. This sequencer
// starts a tone and returns; ctoneTick() (called every game-loop iteration)
// advances/stops steps. Max 6 steps; freq 0 = rest; duty = loudness (8-bit).
struct CipherToneStep { uint16_t freq; uint16_t ms; uint8_t duty; };
CipherToneStep ctQ[6];
int ctLen = 0, ctIdx = 0;
bool ctActive = false;
unsigned long ctStepEnd = 0;

void ctoneStart_() {
  CipherToneStep &s = ctQ[ctIdx];
  if (s.freq == 0) ledcWrite(BUZZER_PIN, 0);
  else { ledcWriteTone(BUZZER_PIN, s.freq); ledcWrite(BUZZER_PIN, s.duty); }
  ctStepEnd = millis() + s.ms;
}
void ctonePlay(const CipherToneStep* seq, int n) {
  ctLen = (n > 6) ? 6 : n;
  for (int i=0; i<ctLen; i++) ctQ[i] = seq[i];
  ctIdx = 0; ctActive = true;
  ctoneStart_();
}
void ctoneTick() {
  if (!ctActive) return;
  if ((long)(millis() - ctStepEnd) < 0) return;
  ctIdx++;
  if (ctIdx >= ctLen) { ledcWrite(BUZZER_PIN, 0); ctActive = false; return; }
  ctoneStart_();
}
void ctoneStop() { ledcWrite(BUZZER_PIN, 0); ctActive = false; }

