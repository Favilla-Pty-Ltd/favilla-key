void queueTurn(bool left) {
  CipherPos base = (turnQN > 0) ? turnQ[turnQN-1] : dir;
  CipherPos t;
  if (left) { t.x =  base.y; t.y = -base.x; }
  else      { t.x = -base.y; t.y =  base.x; }
  if (turnQN < 2) turnQ[turnQN++] = t;
  else            turnQ[1] = t;        // full: the newest press wins the second slot
}
