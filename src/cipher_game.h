  spr.fillRect(cx - 1*s, cy - 3*s, 1*s, 7*s, c);   // stem
  spr.fillRect(cx - 1*s, cy - 3*s, 4*s, 1*s, c);   // top bar
  spr.fillRect(cx - 1*s, cy,       4*s, 1*s, c);   // mid bar
  spr.fillRect(cx - 1*s, cy + 3*s, 4*s, 1*s, c);   // bottom bar
