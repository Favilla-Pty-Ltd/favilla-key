// ── MOMENT FX — short, clock-timed effects that outlive the thing they mark.
// REJECT: the X cuts the dead tile into four wedges that fly apart.
// CHIP:   armour cracks — one corner breaks off.
// BOSS:   51% attack repelled — big wedges, a brass shockwave across the board.
#define FX_REJECT 1
#define FX_CHIP   2
#define FX_BOSS   3
struct CgFx { uint8_t kind, rar, r, g, b; int16_t x, y; unsigned long t0; };
CgFx cgFx[8];
unsigned long cgBotHitAt[5] = {0,0,0,0,0};
void cgFxAdd(uint8_t kind, int gx, int gy, uint8_t r, uint8_t g, uint8_t b, uint8_t rar = 0) {
  int slot = 0; unsigned long oldest = 0xFFFFFFFF;
  for (int i = 0; i < 8; i++) { if (!cgFx[i].kind) { slot = i; break; } if (cgFx[i].t0 < oldest) { oldest = cgFx[i].t0; slot = i; } }
  CgFx& f = cgFx[slot]; f.kind = kind; f.rar = rar; f.r = r; f.g = g; f.b = b;
  f.x = GX + gx*CS + CS/2; f.y = GY + gy*CS + CS/2; f.t0 = cgNow();
}
void cgFxClear(uint8_t kind) { for (int i = 0; i < 8; i++) if (!kind || cgFx[i].kind == kind) cgFx[i].kind = 0; }
void killBot(int idx, int wx, int wy) {
  // Kills cash in the combo (bounty x comboMult) but do NOT refresh the
  // window — only fragments sustain the chain. Hunting a bot mid-chain is
  // a deliberate trade: multiplier payout now vs. clock burned getting it.
  int tierM = (bots[idx].maxHp >= 5) ? 6 : (bots[idx].maxHp > 0 ? bots[idx].maxHp : 1);
  int bounty = (int)(botBounty() * comboMult * tierM * killBountyMult);
  score += bounty; if (score>hi) hi=score;
  {   // REJECTED: the X cuts the tile into four wedges (a boss: brass, with a shockwave)
    uint16_t bc = BOT_COLOR[bots[idx].id];
    if (bots[idx].maxHp >= 5) { cgFxAdd(FX_BOSS, wx, wy, CVR_BRASS_HI); addParticles(wx, wy, cipherRgb(255,225,140), 16, 3.2f); }
    else { cgFxAdd(FX_REJECT, wx, wy, ((bc>>11)&0x1F)<<3, ((bc>>5)&0x3F)<<2, (bc&0x1F)<<3); addParticles(wx, wy, C_WHITE_C, 6, 1.8f); }
  }
  fxBotKill();
  spawnFloater(wx, wy, bounty, FLT_HASH);
  if (bots[idx].maxHp >= 5) {
    runBossKills++;
    // 51% ATTACK repelled — pays 888 (the luck number) and rolls for a LOOK.
    // 11bn: no embers and no looks; the card shows the kill's hash bounty.
    bossCardIsItem = false; bossCardLoot[0] = 0;
    snprintf(bossCardJack,sizeof(bossCardJack),"+%d HASH", (int)bounty);
    bossCardJackN = bounty;
    bossCardStart = cgNow();   // the game holds its breath
  }
  else {
    runBotKills++;   // non-boss bot cracked
    comboBump();     // aggression feeds the chain (careful play used to beat it everywhere)
  }
  satMsgT=60;
  bots[idx].alive=false; bots[idx].respawnTimer=BOT_RESPAWN_TICKS;
}

// Damage a bot — armor absorbs, the finishing blow pays. Cracks recolour
// the bot automatically (render reads CURRENT hp).
void damageBot(int idx, int dmg, int wx, int wy) {
  CipherBot &b = bots[idx];
  if (!b.alive) return;
  if (dmg < 1) dmg = 1;
  if ((int)b.hp > dmg) {
    b.hp -= (uint8_t)dmg;
    cgBotHitAt[idx] = cgNow() | 1;   // white flash on the tile, one corner chips off
    cgFxAdd(FX_CHIP, b.pos.x, b.pos.y, 220, 225, 235);
    addParticles(wx, wy, cipherRgb(200,205,215), 4, 1.8f);
    fxArmorCrack();
    return;
  }
  b.hp = 0;
  killBot(idx, wx, wy);
}

