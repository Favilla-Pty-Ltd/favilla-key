// Start a run under a mode's rules. EVENT uses the loaded event.
void cgStartRun(uint8_t m) {
  if (m == CM_EVENT) cgR = cgEvent; else cgRulesFor(m, cgR);
  if (m == CM_SPEED) {   // 11bk: DAILY, one board a UTC day (the block seed comes next)
    cgSpeedWeekNow = cgDayIndex();
    cgRunBlk = {};
    if (cgDayCurrent()) { cgR.seed = cgblock::seed(g_cgDay); cgRunBlk = g_cgDay; }   // 11bs: the block's board
    else cgR.seed = cgSpeedWeekNow ? cgDaySeed(cgSpeedWeekNow) : 0;   // the date's board (no clock = practice)
    if (cgR.seed && cgDailyBossDay(cgR.seed)) {
      cgKitA1 = SKILL_A_LIGHTNING; cgKitA2 = SKILL_A_ZAP_STORM;
      cgR.bossFirst = 2 + (uint8_t)(cgMix(cgR.seed ^ 0xF125u) % 3u); cgR.bossEvery = 99;   // one boss, block 3 to 5
    } else {
      cgPickKit(cgMix(cgR.seed ? cgR.seed : (uint32_t)esp_random()));
      cgR.bossFirst = 99;   // no boss today
    }
  } else cgPickKit(cgMix((uint32_t)esp_random()));   // FREE PLAY: a random pair every run
  cgSeedOverride = cgR.seed;
  cgHiSnap = hi;
  cgKitApply(cgR.stdKit != 0, cgR.items != 0);
  cgWalletRun = (long)cgR.wallet;
  cgRunLive = true;
  initGame();
  deadCredited = false;
}

// ── Game tick ──────────────────────────────────────────────
void gameTick() {
  // Move bots first (matching HTML order)
  moveBots();

  // ── BOSS PHANTOM — cast and pursuit ─────────────────────────
  {
    bool bossLive = false; int bIdx = -1;
    for (int i=0;i<numBots;i++)
      if (bots[i].alive && bots[i].maxHp >= 5) { bossLive = true; bIdx = i; break; }
    if (bossLive && (long)(cgNow() - bossNextCast) >= 0) {
      bossNextCast = cgNow() + BOSS_CAST_MS;
      bphAlive = true;
      bphPos = bots[bIdx].pos;
      bphUntil = cgNow() + BOSS_PHANTOM_MS;
      bphNextMove = cgNow();
      cipherWarn("PHANTOM", 60);
      addParticles(bphPos.x, bphPos.y, cipherRgb(255,62,45), 12, 3.0f);
      fxDenied();   // the low warning buzz — run
    }
    if (!bossLive) bphAlive = false;   // boss died: projection collapses
    if (bphAlive) {
      if ((long)(cgNow() - bphUntil) >= 0) {
        bphAlive = false;
        addParticles(bphPos.x, bphPos.y, cipherRgb(255,225,140), 8, 2.0f);
      } else if ((long)(cgNow() - bphNextMove) >= 0) {
        bphNextMove = cgNow() + tickRate * 185 / 100;   // clearly slower than you: outrun it
        int sdx = snake[0].x - bphPos.x, sdy = snake[0].y - bphPos.y;
        if (abs(sdx) >= abs(sdy)) bphPos.x += (sdx>0?1:(sdx<0?-1:0));
        else                      bphPos.y += (sdy>0?1:(sdy<0?-1:0));
        addParticles(bphPos.x, bphPos.y, cipherRgb(255,62,45), 1, 1.0f);
        if (bphPos.x == snake[0].x && bphPos.y == snake[0].y) {
          bphAlive = false;
          addParticles(bphPos.x, bphPos.y, cipherRgb(255,225,140), 14, 3.0f);
          takeEnvHit(DC_PHANTOM);   // shield ladder, no bounty — a projection, not a body
          if (cipherDying()) return;
        }
      }
    }
  }

  // ── CONGESTION GRAVITY — the aura DRAGS pickups toward you, one cell
  // every other tick; the 1-cell reach is the visible capture at the end
  // of the drag. Genesis is never pulled: the jackpot demands your body.
  if (auraActive) {
    // Pull rate SCALES WITH THE CHAIN: cold chain = 1 cell per 4 ticks,
    // combo 5+ = per 3, combo 12+ = per 2 (the old full rate). Gravity is
    // strongest exactly when you've earned heat — the network bends
    // around a hot signal.
    static uint8_t auraPullPh = 0;
    auraPullPh++;
    int pullEvery = (combo >= 12) ? 2 : (combo >= 5) ? 3 : 4;
    if ((auraPullPh % pullEvery) == 0) {
      // FRAGMENTS ONLY. Gravity dragging block rewards and blue pickups
      // auto-fed the game's two biggest score events (bench: block 18,
      // 1.45M) — events demand your body; only the chain's food drifts.
      if (hasKey && !(keyPos.x==snake[0].x && keyPos.y==snake[0].y)) {
        int pdx = (keyPos.x - snake[0].x)*CS, pdy = (keyPos.y - snake[0].y)*CS;
        if (pdx*pdx + pdy*pdy <= (long)auraR*auraR) {
          int sx2 = snake[0].x - keyPos.x, sy2 = snake[0].y - keyPos.y;
          if (abs(sx2) >= abs(sy2)) keyPos.x += (sx2>0?1:(sx2<0?-1:0));
          else                      keyPos.y += (sy2>0?1:(sy2<0?-1:0));
          addParticles(keyPos.x, keyPos.y, cipherRgb(224,125,42), 2, 1.2f);
        }
      }
    }
  }

  unsigned long now = cgNow();
  if ((int)(now - lastTick) < stepTick(tickRate)) return;   // 11bq: SAT RUSH steps faster
  lastTick = now;

  if (turnQN > 0) {            // one queued turn per step
    dir = turnQ[0];
    turnQ[0] = turnQ[1];
    turnQN--;
  }
  nd = dir;

  CipherPos hd = snake[0];
  int nx = (hd.x + dir.x + GRID) % GRID;
  int ny = (hd.y + dir.y + GRID) % GRID;

  // Self collision — the tail tip moves out of its cell on this same step,
  // so it only counts when this step GROWS the snake (fragment pickup).
  // Counting it was the #1 cause of death in the sim (~80% of SELF deaths
  // were into the cell the tail was vacating) and read as unfair.
  bool willGrow = hasKey && auraReach(keyPos.x, keyPos.y, nx, ny);
  int selfLim = willGrow ? snakeLen : snakeLen - 1;
  for (int i=1; i<selfLim; i++) {
    if (snake[i].x==nx && snake[i].y==ny) {
      if (takeEnvHit(DC_SELF)) return;   // fatal — stop the tick
      break;                      // shield ate it; i-frames carry us through
    }
  }

  // Fragment expiry — uncollected keys fizzle out and respawn elsewhere
  if (hasKey && (long)(cgNow() - keyExpiry) > 0) {
    addParticles(keyPos.x, keyPos.y, C_GREEN, 5, 1.5f);
    hasKey = false;   // ensureKey() respawns it at end of tick
  }

  // Base shield regen + exposed warning pulse (slow, sparse — distinct
  // from the fast soft-bump combo heartbeat)
  if (!baseShieldUp) {
    if (cgR.regen && (long)(cgNow() - shieldRegenAt) >= 0) {   // HARDCORE: it never comes back
      baseShieldUp = true;
      addParticles(snake[0].x, snake[0].y, cipherRgb(255,190,60), 14, 2.6f);
      fxShieldUp();
      strcpy(satMsg,"SHIELD UP"); satMsgT=40;
    } else if (cipherHapticOn() && (long)(cgNow() - nextVulnPulse) >= 0) {
      haptic.play(HAPTIC_FX_SOFT_TICK);
      nextVulnPulse = cgNow() + 1400;
    }
  }

  // Combo expiry — real-time window (ticks accelerate, humans don't)
  if (combo > 0 && (long)(cgNow() - comboUntil) > 0) {
    if (combo >= 5) fxComboBreak();   // a chain worth keeping just died
    // OVERCLOCK keeps part of the chain; GENESIS BLOCK is a floor it never
    // drops below. (Old effects — a higher cap, a starting combo that timed
    // out — measured +3% for 345k embers.)
    int keep = combo * OC_KEEP_PCT[pasRank(SKILL_P_OVERCLOCK)] / 100;
    int fl = GENESISBLK_ST[pasRank(SKILL_P_GENESIS_BLK)];
    if (keep < fl) keep = fl;
    if (keep > combo) keep = combo;
    if (keep > 0) {
      combo = keep;
      comboMult = min(OVERCLOCK_CAP[pasRank(SKILL_P_OVERCLOCK)], 1.0f + (combo - 1) * COMBO_STEP);
      comboRefresh();
    } else { combo=0; comboMult=1.0f; }
  }

  bool grow=false;
  int pts=0;

  // Key fragment — auraReach: +1 cell pickup radius while CONGESTION is up
  if (hasKey && auraReach(keyPos.x, keyPos.y, nx, ny)) {
    hasKey=false;
    comboBump();                 // fragments are the ONLY combo increment
    txCount++;                   // ...and the only block progress
    float frontMult   = FRONTRUN_MULT[pasRank(SKILL_P_FRONT_RUN)];
    int comboBonus = (int)(txBase() * comboMult * frontMult);
    pts += comboBonus;
    grow = true;
    addParticles(nx, ny, C_GREEN, 8);
    flashTicks = 4;
    fxFragment(combo);
    if (rng(100) < MEMPOOL_PCT[pasRank(SKILL_P_MEMPOOL)]) {
      // BONUS FRAGMENT: this pickup counts twice. (The old proc re-placed a
      // key that ensureKey() refills at the end of every tick anyway — it
      // did nothing.)
      comboBump();
      if (txCount < TXS_PER_BLOCK) txCount++;
      int bonus2 = (int)(txBase() * comboMult * frontMult);
      pts += bonus2;
      spawnFloater(nx, ny, bonus2, FLT_HASH);
    }
    maybeShield();
    maybeSpawnSatoshi();
    spawnFloater(nx, ny, comboBonus, FLT_HASH);
    if (txCount == TXS_PER_BLOCK) {
      strcpy(satMsg,"BLOCK SEALED");
      satMsgT=60;
    }
  }

  // Satoshi fragment — exact cell ALWAYS (the jackpot demands your body)
  if (hasSatoshi && satoshiPos.x==nx && satoshiPos.y==ny) {
    hasSatoshi=false;
    // Deterministic — 10x the current TX base, combo-multiplied. No RNG in
    // the score→ticket path (chance-derived prizes invite gambling scrutiny),
    // and a skill-legible jackpot is the better game anyway: grabbing it at
    // a high combo in a late block is a huge, fully-earned swing.
    int satPts = (int)(10.0f * txBase() * comboMult);
    pts += satPts;
    // No refresh — like kills, the detour costs chain clock. Grab it at a
    // high combo only if you can get back to a fragment in time.
    addParticles(nx, ny, cipherRgb(247,147,26), 18, 3.6f);   // coin spray
    addParticles(nx, ny, C_WHITE_C, 10, 2.2f);
    flashTicks=10;
    fxSatoshi();
    satBurstStart = cgNow(); satBurstX = nx; satBurstY = ny;
    satRushUntil = cgNow() + SAT_RUSH_MS;   // 11bq: SAT RUSH (a second one restarts the clock)
    strcpy(satMsg, "SAT RUSH"); satMsgT = 50;
    satWipe(nx, ny);                        // 11br: and every bot on screen dies (bosses excepted)
    spawnFloater(nx, ny, satPts, FLT_GOLD);
  }

  // Overload pickup — exact cell ALWAYS: mining demands your body
  if (hasOLPick && olPickPos.x==nx && olPickPos.y==ny) {
    hasOLPick=false;
    mineBlock(nx, ny);
    grow=false;
  } else if (hasOLPick && (long)(cgNow() - olSpawnAt) > ORPHAN_MS) {
    // Nobody mined it — the network did. Height advances (bots, speed,
    // the boss schedule) but the coinbase is lost. Without this, refusing
    // to seal block 7 dodged the boss and OUT-scored fighting it (+17-19%).
    hasOLPick=false;
    orphanSeal = true; mineBlock(olPickPos.x, olPickPos.y); orphanSeal = false;
    cipherWarn("ORPHANED", 70);
  }

  // Shield
  if (hasShield && auraReach(shieldPos.x, shieldPos.y, nx, ny)) {
    hasShield=false;
    shieldStack = min(MAX_SHIELDS, shieldStack+1);
    shieldTTL = SHIELD_TTL;
    addParticles(nx, ny, C_PURPLE_C, 10);
    fxShield();
  }

  // Blue chain — exact cell ALWAYS: events demand your body
  if (hasBC && bcPos.x==nx && bcPos.y==ny) {
    hasBC=false;
    collectBlue(bcStage, nx, ny);
  }

  // Move snake
  if (grow && snakeLen < GRID*GRID-1) {
    for (int i=snakeLen; i>0; i--) snake[i]=snake[i-1];
    snakeLen++;
  } else {
    for (int i=snakeLen-1; i>0; i--) snake[i]=snake[i-1];
  }
  snake[0].x=nx; snake[0].y=ny;


  // CipherBot head collision
  for (int i=0;i<numBots;i++) {
    if (bots[i].alive && bots[i].phaseInTicks <= 0 &&
        bots[i].pos.x==nx && bots[i].pos.y==ny) {
      checkBotHit(i, nx, ny);   // phasing bots are intangible both ways
    }
  }

  // Pending death from bot moving into us
  if (pendingDeath) {
    pendingDeath=false;
    // checkBotHit already ran the full shield ladder — this is fatal
    ensureKey(); checkSpawnOLPick();
    deathKind = DC_BOT; deathBotId = pendBotId; deathBotTier = pendBotTier;
    die();
    if (cipherDying()) return;
  }

  // CB trail damage
  if (!hotTicks) {
    for (int i=0;i<numTrailCells;i++) {
      if (trailCells[i].pos.x==nx && trailCells[i].pos.y==ny) {
        ensureKey(); checkSpawnOLPick();
        if (takeEnvHit(DC_TRAIL)) return;
        break;
      }
    }
  }

  // Satoshi msg tick
  // satMsgT now decays per frame in drawFrame (V22.x) — was per game tick

  ensureKey();
  checkSpawnOLPick();
  maybeBroadcast();
  tickBotRespawn();
  tickShield();
  tickBlueChain();
  if (hotTicks>0) hotTicks--;

  if (pts) {
    score+=pts;
    if (score>(int)hi) hi=score;
  }
}

