// ── Armor resists ice ──────────────────────────────────────
// T1 freezes for the full duration, T2 for 75%, T3 for 50% (tier = spawn
// armor, so a cracked T3 stays resistant). BOSSES cannot be frozen at all
// — any freeze becomes a SLOW for the same duration. Used by the DEEP
// FREEZE wave and the blue LOCKDOWN alike.
void freezeApply(int i, unsigned long base) {
  CipherBot &b = bots[i];
  if (b.maxHp >= 5) { b.fwSlowUntil = cgNow() + base; return; }
  unsigned long d = base;
  if      (b.maxHp >= 3) d = d / 2;
  else if (b.maxHp == 2) d = d * 3 / 4;
  b.frozenUntil = cgNow() + d;
}

// ── Blue chain logic ───────────────────────────────────────
void collectBlue(int stage, int wx, int wy) {
  addParticles(wx, wy, C_CHAIN_BLUE, 16, 3.0f);
  addParticles(wx, wy, C_WHITE_C, 8, 2.0f);

  if (stage == 1) {
    blueStage = 1;
    cipherBlueTimer = cgNow() + BLUE_WINDOW_1;
    tickRate = max(MIN_TICK, tickRate - BLUE_SPEED_BOOST);
    blueSpeedBoost++;
    for (int i=0;i<numBots;i++) { bots[i].blueSlow=true; bots[i].blueFreeze=false; }
    spawnNextBlueStage(2);
    fxBlueStage(1);
    strcpy(satMsg, "INTERCEPT");
    satMsgT = 60;

  } else if (stage == 2) {
    blueStage = 2;
    cipherBlueTimer = cgNow() + BLUE_WINDOW_2;
    tickRate = max(MIN_TICK, tickRate - BLUE_SPEED_BOOST);
    blueSpeedBoost++;
    // LOCKDOWN is now a per-bot armored freeze (2.5s base) — T2/T3
    // resist it, bosses only slow, exactly like the DEEP FREEZE wave
    for (int i=0;i<numBots;i++) { bots[i].blueSlow=false; freezeApply(i, 2500); }
    spawnNextBlueStage(3);
    fxBlueStage(2);
    strcpy(satMsg, "LOCKDOWN");
    satMsgT = 60;

  } else if (stage == 3) {
    blueStage = 0; cipherBlueTimer = 0;
    for (int i=0;i<blueSpeedBoost;i++) tickRate = min(TICK_TABLE[min(overloads,TICK_TABLE_LEN-1)], tickRate+BLUE_SPEED_BOOST);
    blueSpeedBoost = 0;
    // 1-damage doctrine: the broadcast hits EVERY bot for exactly 1, at
    // double bounty per kill. Bare bots die; armor survives it, cracked —
    // a block-11 board eats the blast and keeps coming, thinner-skinned.
    int count = 0;
    killBountyMult = 2.0f;
    for (int i=0;i<numBots;i++) {
      if (!bots[i].alive || bots[i].phaseInTicks > 0) continue;
      if (bots[i].maxHp >= 5) continue;   // bosses shrug the broadcast — skills only
      addParticles(bots[i].pos.x, bots[i].pos.y, C_CHAIN_BLUE, 12, 2.5f);
      bool wasAlive = bots[i].alive;
      damageBot(i, 1, bots[i].pos.x, bots[i].pos.y);
      if (wasAlive && !bots[i].alive) count++;
    }
    killBountyMult = 1.0f;
    numTrailCells = 0;
    hasBC=false;
    fxBroadcast();
    snprintf(satMsg, sizeof(satMsg), "BROADCAST %d", count);
    satMsgT=90;
  }
}

