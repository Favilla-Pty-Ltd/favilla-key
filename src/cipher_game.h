void checkBotHit(int idx, int wx, int wy) {
  // BOSSES only take damage from SKILLS (dash, bolts, detonation, the
  // freeze-execute, the clone). Contact — hot, shielded, or otherwise —
  // never hurts one: your shield physics still apply to YOU, but the
  // monster doesn't blink. Charging a boss is paying, not fighting.
  bool bossHit = (bots[idx].maxHp >= 5);
  if (hotTicks > 0) {
    if (bossHit) {   // CLANG — you pass through; it shrugs
      addParticles(wx, wy, cipherRgb(255,225,140), 6, 2.0f);
      if (cipherHapticOn()) haptic.play(HAPTIC_FX_SOFT_TICK);
      return;
    }
    // Hot contact: 1 damage; armored survivors are SHOCKED in place —
    // stunned ~0.75s, cracked, and lined up for a follow-up.
    damageBot(idx, 1, wx, wy);
    if (bots[idx].alive) bots[idx].frozenUntil = cgNow() + 750;
    return;
  }
  // SHATTER: a FROZEN bot cracks on contact and costs no shield — DEEP
  // FREEZE's identity is freeze-then-smash. (Bosses are slowed, never frozen.)
  if (!bossHit && (long)(cgNow() - bots[idx].frozenUntil) < 0) {
    damageBot(idx, 1, wx, wy);
    return;
  }
  // Damage ladder: i-frames -> overshield -> base shield -> fatal.
  // Every shield layer burns the attacker out for full bounty.
  if ((long)(cgNow() - invulnUntil) < 0) return;
  if (shieldStack > 0) {
    shieldStack--;
    if (!bossHit) damageBot(idx, 1, wx, wy);
    snprintf(satMsg,sizeof(satMsg),"ABSORBED %d",shieldStack);
    satMsgT=50;
    return;
  }
  if (baseShieldUp) {
    baseShieldUp  = false;
    shieldRegenAt = cgNow() + shieldRegenDelay();
    invulnUntil   = cgNow() + SHIELD_IFRAME_MS;
    nextVulnPulse = cgNow() + 900;
    if (!bossHit) damageBot(idx, 1, wx, wy);   // the breach cracks the attacker
    fxShieldBreak();
    cipherWarn("SHIELD DOWN", 50);
    flashTicks = 6;
    return;
  }
  pendingDeath=true; pendingDeathPos.x=wx; pendingDeathPos.y=wy;
  pendBotId = (uint8_t)bots[idx].id; pendBotTier = bots[idx].maxHp;
}

// ── Death ──────────────────────────────────────────────────
void die() {
  // A hit landed with everything down — fatal, unless SEED RESTORE
  // (CHECKPOINT) cheats it: instant shield restore, chain kept, i-frames.
  if (checkpointsLeft > 0) {
    checkpointsLeft--;
    baseShieldUp = true;
    invulnUntil  = cgNow() + SHIELD_IFRAME_MS;
    if (combo > 0) comboUntil = cgNow() + comboWindowMs() + 2000;
    addParticles(snake[0].x, snake[0].y, 0x57FF, 16, 3.0f);
    fxShieldUp();
    strcpy(satMsg,"SEED RESTORE");
    satMsgT=60;
    return;
  }
  if (itemEqIsDef(8)) {                // NOVA BURST — death burst by style
    int ns = itemFx(8);
    numParts = 0;                      // the burst owns the whole pool
    uint16_t nc = cipherRgb(COSM_SWATCH[2][ns][0], COSM_SWATCH[2][ns][1], COSM_SWATCH[2][ns][2]);
    addParticles(snake[0].x, snake[0].y, nc, 28 + ns*6, 3.5f + ns*0.8f);
    if (ns == 2) addParticles(snake[0].x, snake[0].y, cipherRgb(255,215,80), 8, 2.0f);
  } else if (itemEqIsDef(12)) {          // SHATTER — the snake becomes falling hex digits
    int ss = itemFx(12);
    numParts = 0; numGlyphs = 0;
    for (int i = 0; i < snakeLen && numGlyphs < 28; i += max(1, snakeLen/24)) {
      float a = (float)random(628)/100.0f, sp = 0.6f + (float)random(100)/60.0f;
      glyphs[numGlyphs++] = { (float)(GX + snake[i].x*CS + CS/2 - 3), (float)(GY + snake[i].y*CS + CS/2 - 5),
                              cosf(a)*sp, sinf(a)*sp - 0.6f, 1.0f, (uint8_t)random(16) };
    }
    shatterSwatch = ss;
  } else {
    addParticles(snake[0].x, snake[0].y, C_RED, 24, 3.5f);
  }
  combo=0; comboMult=1.0f;
  if (score>hi) hi=score;
  fxDeath();    // the sound lands at the hit, not 450 ms later on the dead screen
  dyingUntil = cgNow() + (itemEqIsDef(12) ? 950UL : (unsigned long)DEATH_HOLD_MS);   // hit-stop; PH_PLAYING promotes to PH_DEAD (SHATTER holds longer)
}

// Environmental damage (own tail, CB trail): same uniform ladder as bots —
// overshield, then base shield, then fatal — but pays no bounty.
// Returns true if the hit ended the run (caller must stop the tick).
bool takeEnvHit(uint8_t cause) {
  if ((long)(cgNow() - invulnUntil) < 0) return false;
  if (shieldStack > 0) {
    shieldStack--;
    snprintf(satMsg,sizeof(satMsg),"ABSORBED %d",shieldStack);
    satMsgT=50;
    return false;
  }
  if (baseShieldUp) {
    baseShieldUp  = false;
    shieldRegenAt = cgNow() + shieldRegenDelay();
    invulnUntil   = cgNow() + SHIELD_IFRAME_MS;
    nextVulnPulse = cgNow() + 900;
    fxShieldBreak();
    cipherWarn("SHIELD DOWN", 50);
    flashTicks = 6;
    return false;
  }
  deathKind = cause;
  die();
  return cipherDying();   // SEED RESTORE may have cheated it
}

// ── Move bots ──────────────────────────────────────────────
void moveBots() {
  CipherPos hd = snake[0];
  CipherPos chaseTarget = (forkAlive && cgNow()<forkUntil) ? forkDecoy : hd;
  CipherPos keyTarget = hasKey ? keyPos : chaseTarget;
  unsigned long now = cgNow();
  float chaseRamp = min(1.0f, overloads / 10.0f) * DARKPOOL_FACT[pasRank(SKILL_P_DARK_POOL)];
  int ol = overloads;

  // Clear trail cells
  numTrailCells = 0;

  for (int i=0; i<numBots; i++) {
    CipherBot& b = bots[i];
    if (!b.alive) continue;

    // Collect CB trails
    if (b.id == BOT_CB) {
      for (int t=0;t<b.trailLen;t++) {
        b.trail[t].ttl--;
        if (b.trail[t].ttl > 0 && numTrailCells<48) {
          { CipherTrailCell tc; tc.pos=b.trail[t].pos; tc.ttl=b.trail[t].ttl; trailCells[numTrailCells++]=tc; }
        }
      }
      // Remove expired
      int nl=0;
      for (int t=0;t<b.trailLen;t++) if (b.trail[t].ttl>0) b.trail[nl++]=b.trail[t];
      b.trailLen=nl;
    }

    if (b.blueFreeze) continue;
    if ((long)(cgNow() - b.frozenUntil) < 0) continue;   // iced by the wave

    // Phase-in — bot is materialising, skip movement and collision
    if (b.phaseInTicks > 0) { b.phaseInTicks--; continue; }

    int spd = max((int)(tickRate*1.05f), BOT_BASESPEED[b.id] - ol*8);
    if (b.blueSlow) spd = (int)(spd / 0.4f);
    if (auraActive) {   // CONGESTION — slow scales with rank (37/44/50%)
      int abx = (b.pos.x - hd.x)*CS, aby = (b.pos.y - hd.y)*CS;
      if (abx*abx + aby*aby <= auraR*auraR)
        spd = spd * AURA_SLOW_NUM[skillRankA[SKILL_A_CONGESTION]] / 5;
    }
    if (b.maxHp >= 5) spd = spd*13/10;   // bosses lumber — tanky, not quick
    if ((long)(cgNow() - b.fwSlowUntil) < 0) spd = spd*8/5;   // iced boss: slowed, never stopped
    if ((int)(now - b.lastMove) < spd) continue;
    b.lastMove = now;

    if (BOT_TYPE[b.id] == TYPE_STATIONARY) {
      // Check if it hit the snake
      if (b.pos.x==hd.x && b.pos.y==hd.y) checkBotHit(i, b.pos.x, b.pos.y);
      continue;
    }

    int oldX=b.pos.x, oldY=b.pos.y;
    float chaseRatio = BOT_BASECHASE[b.id] + (0.85f-BOT_BASECHASE[b.id])*chaseRamp;
    b.tell = false;

    int dx=0, dy=0;

    if (BOT_TYPE[b.id] == TYPE_FASTCHASE) {
      b.tell=true;
      dx=hd.x-b.pos.x; dy=hd.y-b.pos.y;
      if (abs(dx)>=abs(dy)) { dx=(dx>0?1:-1); dy=0; }
      else { dx=0; dy=(dy>0?1:-1); }

    } else if (BOT_TYPE[b.id] == TYPE_KEYHUNTER) {
      CipherPos tgt = (rng(100)<70) ? keyTarget : hd;
      if ((float)rng(100)/100.0f < chaseRatio) {
        b.tell=true;
        dx=tgt.x-b.pos.x; dy=tgt.y-b.pos.y;
        if (abs(dx)>=abs(dy)) { dx=(dx>0?1:-1); dy=0; }
        else { dx=0; dy=(dy>0?1:-1); }
      } else {
        int dirs[4][2]={{1,0},{-1,0},{0,1},{0,-1}};
        int d=rng(4); dx=dirs[d][0]; dy=dirs[d][1];
      }

    } else {
      // TYPE_CHASE or TYPE_TRAIL
      if ((float)rng(100)/100.0f < chaseRatio) {
        b.tell=true;
        dx=chaseTarget.x-b.pos.x; dy=chaseTarget.y-b.pos.y;
        if (abs(dx)>=abs(dy)) { dx=(dx>0?1:-1); dy=0; }
        else { dx=0; dy=(dy>0?1:-1); }
      } else {
        int dirs[4][2]={{1,0},{-1,0},{0,1},{0,-1}};
        int d=rng(4); dx=dirs[d][0]; dy=dirs[d][1];
      }
    }

    // Post-block hot window: the player is lethal, so bots FLEE instead of
    // chasing — running at a live wire is silly. Overrides every mobile type.
    if (hotTicks > 0) {
      b.tell = false;
      dx = b.pos.x - hd.x; dy = b.pos.y - hd.y;   // directly away from the head
      if (dx == 0 && dy == 0) { dx = rng(2) ? 1 : -1; dy = 0; }
      if (abs(dx) >= abs(dy)) { dx = (dx > 0 ? 1 : -1); dy = 0; }
      else                    { dx = 0; dy = (dy > 0 ? 1 : -1); }
    }

    int nx=(b.pos.x+dx+GRID)%GRID;
    int ny=(b.pos.y+dy+GRID)%GRID;

    // Add trail cell for CB bot before moving
    if (b.id==BOT_CB && b.trailLen<16) {
      { CipherTrailCell tc; tc.pos.x=oldX; tc.pos.y=oldY; tc.ttl=8; b.trail[b.trailLen++]=tc; }
    }

    b.pos.x=nx; b.pos.y=ny;
    if (b.labelT>0) b.labelT--;

    // Hit snake head?
    if ((nx==hd.x && ny==hd.y) || (oldX==hd.x && oldY==hd.y)) {
      checkBotHit(i, nx, ny);
    }
  }
}

// ── CipherBot respawn tick ───────────────────────────────────────
void tickBotRespawn() {
  bool anyAlive=false;
  for (int i=0;i<numBots;i++) {
    if (bots[i].alive) { anyAlive=true; }
    else if (bots[i].respawnTimer>0) {
      bots[i].respawnTimer--;
      if (bots[i].respawnTimer==0) spawnBot(bots[i].id);
    }
  }
  if (!anyAlive) {
    botRespawnTimer++;
    if (botRespawnTimer >= BOT_RESPAWN_TICKS) {
      botRespawnTimer=0;
      spawnHostiles();
    }
  } else {
    botRespawnTimer=0;
  }
}

