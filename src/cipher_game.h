// ── Frame pacing ────────────────────────────────────────────────────────────
// The play loop used to run flat out (vTaskDelay(1)), so every frameCount-
// keyed animation — breathing, pulses, flicker, floater rise — changed speed
// with scene complexity, and the CPU sat at 100% for nothing. Cap at ~30 fps:
// stable timing, and the idle gaps are where the radio and the watchdog get
// serviced anyway.
#define CIPHER_FRAME_MS 33
void cipherFrameWait(unsigned long frameStart) {
  pmBacklightTick();   // 4 Oct 2026 (PM build): CIPHER never returns to loop(), so keep the
                       // lit/no-light-sleep lock current here - a nap inside this wait pauses
                       // the backlight PWM (LEDC on APB) and showed as screen flicker.
  long left = (long)CIPHER_FRAME_MS - (long)(millis() - frameStart);
  if (left > 0) vTaskDelay(left / portTICK_PERIOD_MS);
  else          vTaskDelay(1 / portTICK_PERIOD_MS);
}
// Spend one banked logic step, if there is one.
static inline bool cgStep() {
  if (cgAcc < (unsigned long)CIPHER_FRAME_MS) return false;
  cgAcc -= CIPHER_FRAME_MS; cgClock += CIPHER_FRAME_MS;
  return true;
}
