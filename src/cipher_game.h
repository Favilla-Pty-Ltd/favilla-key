// The nearest skill purchase: "UPGRADE READY" if one is affordable now,
// else the smallest ember gap. Equipped skills are preferred. The
// one-more-run hook the dead screen never had.
bool cipherNextGoal(char* out, size_t n, bool* ready) {
  int bestGap = 0x7FFFFFFF; bool bestEq = false; char name[24] = ""; int bestR = 0; bool found = false;
  for (int pass = 0; pass < 2 && !found; pass++) {           // pass 0 = equipped only
    for (int k = 1; k <= N_ACTIVE + N_PASSIVE; k++) {
      bool isA = k <= N_ACTIVE; int id = isA ? k : k - N_ACTIVE;
      if (!isA && pasRetired(id)) continue;
      bool eq = isA ? (skillActive == id || skillActive2 == id) : (skillPassive1 == id || skillPassive2 == id);
      if (pass == 0 && !eq) continue;
      int rank = isA ? skillRankA[id] : skillRankP[id];
      if (rank >= 3) continue;
      int toR = rank + 1;
      if (cipherLvl < skillLevelReq(isA, id, toR)) continue;
      int cost = (toR == 1) ? skillBuyCost(isA, id) : skillRankCost(isA, id, toR);
      int gap = cost - (int)min(embers, 0x7FFFFFFFL);
      if (gap < bestGap) { bestGap = gap; bestEq = eq; bestR = toR;
        strncpy(name, isA ? SKILL_A_NAMES[id] : SKILL_P_NAMES[id], sizeof(name)-1); found = true; }
    }
  }
  if (!found) return false;
  *ready = bestGap <= 0;
  if (*ready) snprintf(out, n, "UPGRADE READY  %s R%d", name, bestR);
  else { char g[16]; fmtEmbers(bestGap, g, sizeof(g)); snprintf(out, n, "%s TO %s R%d", g, name, bestR); }
  (void)bestEq;
  return true;
}
