void triggerActive(int slot) {
  int sk = slotSkill(slot);
  if (sk == SKILL_A_NONE) return;
  if (!slotAvailable(slot)) return;
  // Actives cost embers per use. Denied fires feedback but does NOT burn
  // the cooldown — you can fire the moment you can afford it.
  int useCost = activeUseCost(sk);
  if (!cipherSpendEmbers(useCost)) {
    { char nb2[16]; snprintf(nb2,sizeof(nb2),"NEED %d",useCost); cipherWarn(nb2, 45); }
    fxDenied();
    return;
  }
  if (useCost > 0) {
    runEmberDelta -= useCost;
    spawnFloater(snake[0].x, snake[0].y, useCost, FLT_EMBER_NEG);
  }
  slotFired(slot, 0);
  fxSkillFire();
  unsigned long now = cgNow();

  if (sk == SKILL_A_LIGHTNING) {
    // Dash 3 blocks in current direction, phase through bots
    int lastX = snake[0].x, lastY = snake[0].y;
    int dashedX[5], dashedY[5];
    int dashCount = 0;
    int burstHits = 0;   // everything struck in this ONE bolt
    int dashMax = LIGHTNING_CELLS[skillRankA[sk]];
    for (int d = 0; d < dashMax; d++) {
      int nx = (lastX + dir.x + GRID) % GRID;
      int ny = (lastY + dir.y + GRID) % GRID;
      bool selfHit = false;
      for (int i = 1; i < snakeLen; i++)
        if (snake[i].x == nx && snake[i].y == ny) { selfHit = true; break; }
      if (selfHit) break;
      dashedX[d] = nx; dashedY[d] = ny;
      dashCount++;
      // LIGHTNING destroys and collects EVERYTHING it passes through —
      // bots, fragments, shields, Genesis, blue pickups, even the block
      // reward (mining mid-dash is the dream play). Shared with ZAP STORM.
      burstHits += sweepCell(nx, ny, true);    // the dash FEEDS the chain
      lastX = nx; lastY = ny;
    }
    if (dashCount > 0) {
      // Shift snake body
      for (int i = snakeLen - 1; i >= dashCount; i--) snake[i] = snake[i - dashCount];
      for (int d = 0; d < dashCount; d++) {
        snake[d].x = dashedX[dashCount - 1 - d];
        snake[d].y = dashedY[dashCount - 1 - d];
      }
      // Bolt burst — pure particles along the path (the old lingering
      // bolt-cell overlay is gone: it was an eyesore AND an out-of-bounds
      // write once the dash grew past 3 cells)
      for (int d = 0; d < dashCount; d++)
        addParticles(dashedX[d], dashedY[d], cipherAlpha(0, 220, 255, 1.0f), 10, 3.5f);
      flashTicks = 8;

      // Burst reward — bolts often MISS (and you pay per bolt either way), so
      // landing them pays back. LINEAR base (2 embers/hit): a well-aimed cast
      // nets positive, a spray-and-miss cast nets negative. Was quadratic — a
      // money printer. On top of the base, big multi-hit casts snap to MEME
      // JACKPOTS (+69 at 6 hits, +420 at 10+). These are FLAT one-shot bonuses,
      // not multipliers, so they stay exploit-safe: you must land a huge bolt
      // spread (hard, and every bolt was paid for) to trigger them.
      if (burstHits >= 2) {
        long burstEmb = 2L * (long)burstHits;   // linear base
        if (burstHits >= 10)     burstEmb = 420; // monster chain — meme jackpot
        else if (burstHits >= 6) burstEmb = 69;  // big burst — meme jackpot
        (void)burstEmb;   // 11bn: no embers
        fxComboMilestone(3 * burstHits);   // jingle pitch scales with the burst
      }
      // THE CONDUIT: every target struck refunds cooldown on BOTH slots —
      // 30% of the full clock per hit, capped at 90% for a triple. A
      // loaded dash hands your kit back: the payoff skills orbit the
      // builder, and LIGHTNING pairs finally answer aura/freeze pairs.
      if (burstHits > 0) {
        int h3 = (burstHits > 3) ? 3 : burstHits;
        float rp = 30.0f;
        unsigned long refund = (unsigned long)((float)ACTIVE_CD_MS * rp * (float)h3 / 100.0f);
        activeLastUsed  = (activeLastUsed  > refund) ? activeLastUsed  - refund : 0;
        activeLastUsed2 = (activeLastUsed2 > refund) ? activeLastUsed2 - refund : 0;
        snprintf(satMsg,sizeof(satMsg),"CONDUIT -%d%%", 30*h3); satMsgT=45;
      }
    }
  } else if (sk == SKILL_A_DEEP_FREEZE) {
    fwActive = true; fwStart = now;
    fwX = GX + snake[0].x*CS + CS/2;
    fwY = GY + snake[0].y*CS + CS/2;
    fwDur = FREEZE_MS[skillRankA[sk]];
    for (int i=0;i<numBots;i++) bots[i].fwHit = false;   // fresh wave
    fwCanKey=hasKey; fwCanBC=hasBC;
    fxDeepFreeze();
    strcpy(satMsg,"FROZEN"); satMsgT=50;
  } else if (sk == SKILL_A_CONGESTION) {
    auraActive = true;
    auraSlot = slot;
    auraR = AURA_RADIUS_PX[skillRankA[sk]];
    auraNextDrain = now + 1000;
    fxAuraOn();
    strcpy(satMsg,"CONGESTION"); satMsgT=45;
  } else if (sk == SKILL_A_FORK) {
    forkDecoy = snake[0];             // the clone splits FROM you
    forkAlive = true;
    forkLastMove = now;
    forkTrailLen = 0;
    {
      // Lifetime = rank base + the chain: 0.3s per combo stack at cast.
      // A capped chain more than doubles the clone's life — FORK joins
      // ZAP STORM in spending the combo you built.
      long fl = FORK_MS[skillRankA[sk]] + (long)combo * FORK_MS_PER_COMBO;
      if (fl > FORK_MS_CAP) fl = FORK_MS_CAP;
      forkUntil = now + fl;
      fxForkSplit();
      addParticles(snake[0].x,snake[0].y,C_PINK_BOT,12,2.5f);
      snprintf(satMsg,sizeof(satMsg),"FORK %dS",(int)(fl/1000)); satMsgT=50;
    }
  }
}

