// 11bu: when online, DAILY asks for the newest block on its first opening after
// power-on, then at most every CG_DAY_ASK_MS. A block the site (or the app,
// from the site) gave as the newest is today's whatever its age: a day of 144
// blocks can run past CG_DAY_FRESH_S. It stays today's for CG_DAY_FRESH_S after
// it arrived, unless a newer one comes. Nothing is fetched at boot: the KEY
// only contacts favillakey.io when CIPHER's DAILY is opened.
#define CG_DAY_ASK_MS (10UL * 60UL * 1000UL)
static bool     cgDayLatest = false;  static uint32_t cgDayLatestMs = 0;
static bool     cgDayAsked = false;   static uint32_t cgDayAskedMs = 0;
static inline int64_t cgNowUnix() { time_t n; time(&n); return ((long)n > 1700000000L) ? (int64_t)n : 0; }
bool cgDayCurrent() {
  if (!g_cgDay.valid) return false;
  if (cgDayLatest && millis() - cgDayLatestMs < (uint32_t)CG_DAY_FRESH_S * 1000UL) return true;
  int64_t now = cgNowUnix();
  return now == 0 || (now - (int64_t)g_cgDay.time) < CG_DAY_FRESH_S;
}
// Ask now? Not when the newest arrived (or was asked for) under 10 minutes ago.
bool cgDayAskDue() {
  if (cgDayLatest && millis() - cgDayLatestMs < CG_DAY_ASK_MS) return false;
  return !cgDayAsked || millis() - cgDayAskedMs >= CG_DAY_ASK_MS;
}
void cgDaySave() {
  Preferences p; p.begin("cipher", false, NVSPART_GAME);
  p.putUInt("dayH", g_cgDay.height);
  p.putBytes("dayB", g_cgDay.header, 80);
  p.end();
}
// Take a block given as text (fetch, the phone or a QR). true when it verified
// and is not older than the one held; a newer one is kept. latest: it came from
// the site as its newest (11bu), so it is today's whatever its age.
bool cgDayOffer(const char* text, bool latest) {
  CgBlock b;
  if (!cgblock::parse(text, cgNowUnix(), b)) return false;
  if (g_cgDay.valid && b.height < g_cgDay.height) return false;   // never step back a day
  if (!g_cgDay.valid || b.height != g_cgDay.height) { g_cgDay = b; cgDaySave(); }
  if (latest) { cgDayLatest = true; cgDayLatestMs = millis(); }
  return true;
}
void cgDayLoad() {
  Preferences p; p.begin("cipher", true, NVSPART_GAME);
  uint32_t h = p.getUInt("dayH", 0); uint8_t hdr[80];
  size_t got = p.getBytes("dayB", hdr, sizeof hdr);
  p.end();
  g_cgDay.valid = false;
  if (!h || got != 80) return;
  char t[16 + 161]; int k = snprintf(t, sizeof t, "%lu,", (unsigned long)h);
  static const char* H = "0123456789abcdef";
  for (int i = 0; i < 80; i++) { t[k++] = H[hdr[i] >> 4]; t[k++] = H[hdr[i] & 15]; }
  t[k] = 0;
  cgblock::parse(t, 0, g_cgDay);   // proof of work again; age is judged by cgDayCurrent()
}
// Before a daily run, when cgDayAskDue(): ask favillakey.io (over Wi-Fi or
// through the phone) for the newest block. true when a current block is held,
// the fetched one or, if the fetch failed, the one already held.
bool cgEnsureDay() {
  if (!cipherFetchDayHook) return cgDayCurrent();
  cgDayAsked = true; cgDayAskedMs = millis();
  char buf[200];
  if (cipherFetchDayHook(buf, sizeof buf)) cgDayOffer(buf, true);
  return cgDayCurrent();
}
uint32_t cgDayIndex() {
  if (cgDayCurrent()) return 0x40000000u | (g_cgDay.height / CG_BLOCK_DAY);   // block days never equal clock days
  time_t now; time(&now);
  if ((long)now < 1700000000L) return 0;
  return (uint32_t)(((long)now - 1704067200L) / 86400L) + 1;
}
uint32_t cgDaySeed(uint32_t day) {
  uint32_t h = 0x811C9DC5u ^ 0x43444159u;            // "CDAY"
  for (int i = 0; i < 4; i++) { h ^= (day >> (8 * i)) & 0xFF; h *= 16777619u; }
  return h ? h : 1;
}
