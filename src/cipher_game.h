// All ember credits come through here so future sources (steps) share the
// same path. NOTE: the old "credits are rare (once per run/day)" assumption
// died when the pedometer landed — steps credit every 30s poll while walking.
// Credits therefore accumulate in RAM and are flushed by the nv_domains
// batching engine (cipherFlushHot in cipher_steps.h): at most once per
// NV_GAME_FLUSH_MS, never during a security flow, and unconditionally on
// death/exit/sleep. Loss/double-credit window is bounded and local-only.
void cipherAddEmbers(long n, uint8_t src) {
  (void)n; (void)src; return;   // 11bn: no economy; nothing earns or keeps embers
  if (n <= 0) return;
  if (cgSandbox() && src == EMBER_SRC_GAME) { cgWalletRun += n; return; }   // sandbox runs pay the run wallet
  // BOOT-ORDER GUARD: steps credit from loop() within seconds of boot, long
  // before runCipherGame() ever runs. Crediting into never-loaded RAM (cold
  // zeros) and then flushing would overwrite the stored balance with just
  // the steps walked since boot — a de-facto wipe. Load first, always.
  if (!cipherStateLoaded) { cipherLoadState(); cipherStateLoaded = true; }
  embers += n;
  if (src == EMBER_SRC_STEPS) embersWalked += n;   // PROOF OF WALK ledger
  nvMarkGameDirty();
}

// Spend embers. Same path as credits: RAM is authoritative, the nv_domains
// batching engine flushes (at most once per NV_GAME_FLUSH_MS, and always on
// death / exit / sleep). The old "persist immediately" version opened NVS on
// EVERY spend — fine for shop purchases, but CONGESTION upkeep spends once a
// second and ZAP once per cast, so holding the aura wrote flash at 1 Hz. A
// flash write stalls the core for milliseconds, which was a visible frame
// hitch every second on top of the wear. Shop paths call nvGameFlushNow()
// after a purchase so a bought skill and its price land together.
bool cipherSpendEmbers(long n) {
  (void)n; return true;   // 11bn: no economy; nothing costs embers
  if (n <= 0) return true;
  if (cgSandbox()) { if (cgWalletRun < n) return false; cgWalletRun -= n; return true; }
  if (!cipherStateLoaded) { cipherLoadState(); cipherStateLoaded = true; }
  if (embers < n) return false;
  embers -= n;
  nvMarkGameDirty();
  return true;
}

