// ── Ephemeral relay link for sharing ─────────────────────────────────────────
// The V22.x single-TLS doctrine keeps webSocket2 deliberately idle during
// bunker operation — which makes it the perfect vehicle here: bring it up to a
// general relay just for the publish, then tear it down, leaving the device's
// connection state exactly as we found it. publishEvent()'s ws2 send path is
// unconditional (no bunker-only-kind skip), so kinds 1888/1 flow through it.
// FAILOVER order, not a broadcast list — cipherShareOpenLink() stops at the
// first relay that connects, so exactly ONE of these ever receives a score.
// relay.favillakey.io is therefore FIRST: it exists specifically because the
// public relays purge kind-1888 (retention / spam filtering), which is what
// made the archive necessary in the first place. With it second or absent, the
// canonical archive only ever gets a score when Primal happens to be down —
// i.e. almost never, which was the situation before this change.
// The public relays stay as fallbacks so a run is still shareable if ours is
// unreachable.
static const char* CIPHER_SHARE_RELAYS[] = { "relay.favillakey.io", "relay.primal.net", "nos.lol" };

// Share-OK watch (defined in main.cpp, before wsEvent2). Set the id we want a
// relay OK for, clear the flags, publish, then pump until g_shareOkGot.
extern char g_shareWaitId[65];
extern volatile bool g_shareOkGot;
extern volatile bool g_shareOkAccepted;
extern volatile bool g_cipherShareLink;   // ws2 is publish-only while true

// Publish ONE signed event and wait up to timeoutMs for a relay OK on its id.
// Returns true only if a relay actually accepted it. Pumps ws2 so the RX path
// runs. This is what makes SHARED mean "a relay took it", not "we sent bytes".
static bool cipherPublishConfirmed(const char* signedJson, int timeoutMs){
  char eid[65] = {0};
  { JsonDocument d; if(deserializeJson(d, signedJson)) return false;
    strlcpy(eid, d["id"] | "", sizeof(eid)); }
  if(!eid[0]) return false;
  strlcpy(g_shareWaitId, eid, sizeof(g_shareWaitId));
  g_shareOkGot = false; g_shareOkAccepted = false;
  if(!publishEvent(signedJson)){ g_shareWaitId[0]=0; return false; }
  unsigned long t0 = millis();
  while(millis() - t0 < (unsigned long)timeoutMs){
    webSocket2.loop();
    esp_task_wdt_reset();
    if(g_shareOkGot) break;
    delay(20);
  }
  bool ok = g_shareOkGot && g_shareOkAccepted;
  g_shareWaitId[0] = 0;
  return ok;
}

