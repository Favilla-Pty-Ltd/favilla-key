// ── Mine a sealed block ──────────────────────────────────────
// Shared by normal collection and the LIGHTNING sweep. Pays the coinbase
// (combo- and HODL-multiplied), advances the height, wipes the mempool,
// shrinks the body, and keeps a live chain breathing through the reset.
void mineBlock(int nx, int ny) {
  int blockReward = orphanSeal ? 0 :
                    (int)((1000 + 500*overloads) * comboMult * HODL_MULT[pasRank(SKILL_P_HODL)]);
  overloads++;
  if (cgR.target && overloads >= cgR.target && !cgRunFinished) {   // SPEED RUN finish line
    cgRunFinished = true; cgFinishMs = cgNow() - runStartMs;
    dyingUntil = cgNow() + 700;          // the hit-stop path ends the run cleanly
  }
  int ti = min(overloads, TICK_TABLE_LEN-1);
  tickRate = TICK_TABLE[ti];
  // Bots PERSIST across the seal — the mempool doesn't forget. spawnHostiles
  // below only TOPS UP to the new block's cap. Cracked armor stays cracked.
  numTrailCells=0;   // the CB trail does clear — fresh hazard slate

  // ...and survivors HARDEN: every bot alive at the seal gains +1 armor
  // (hp AND maxHp, capped at 4 — one shy of boss class, so hardening can
  // never mint boss bounties or farm the item faucet). Sealing without
  // sweeping makes the next block meaner but RICHER: bounty pays by tier.
  for (int i=0;i<numBots;i++) {
    if (bots[i].alive && bots[i].maxHp < 4) {
      bots[i].maxHp++; bots[i].hp++;
      addParticles(bots[i].pos.x, bots[i].pos.y, cipherRgb(172,182,202), 6, 2.0f);
    }
  }
  score += blockReward; if (score > (int)hi) hi = score;
  spawnFloater(nx, ny, blockReward, FLT_HASH);
  hotTicks=30;   // outlives the 18-tick bot phase-in — real flee window
  txCount=0;
  // Combo PERSISTS across the block — grace covers the board reset
  if (combo > 0) comboUntil = cgNow() + comboWindowMs() + BLOCK_GRACE_MS;
  addParticles(nx, ny, C_WHITE_C, 32, 4.0f);
  addParticles(nx, ny, C_YELLOW_OL, 20, 3.0f);
  addParticles(nx, ny, C_AMBER, 16, 2.0f);
  flashTicks=14;
  fxOverload();
  snakeLen = MIN_SIZE;   // always shrink — HODL boosts block rewards now
  // (COLD STORAGE's sealed-with-overshield bonus is gone: Phase 2 turns that
  // passive into LUCKY NONCE — item luck — see killBot.)
  bossDoneThisBlock = false;
  spawnHostiles();
  // BOSS blocks: B8, B11, B14... — one spawned bot gets promoted
  if (cgBossBlock(overloads)) {   // NORMAL: B8, B11, B14... (BOSS RUN: every block)
    for (int i=0;i<numBots;i++) {
      if (bots[i].alive && bots[i].maxHp < 5) {   // don't re-armor a surviving boss
        bots[i].hp = bots[i].maxHp = 5;
        bossDoneThisBlock = true;
        break;
      }
    }
  }
  snprintf(satMsg,sizeof(satMsg),"BLOCK %d", overloads);
  satMsgT=70;
}

// ── Sweep a cell — shared by the LIGHTNING dash and ZAP STORM bolts ──
// Kills non-phasing bots (full bounty x combo) and collects everything
// present: fragments (full TX), shields, Genesis, blue pickups, and the
// block reward. Returns how many things were struck.
//
// chainCharge (LIGHTNING dash ONLY): everything struck feeds the chain —
// a swept TX is worth 3 stacks, everything else +1 each. Threading a
// loaded lane is the combo play. ZAP bolts pass false: the storm SPENDS
// the chain (bolts = combo), so letting it also BUILD combo would be a
// self-amplifying loop.
int sweepCell(int nx, int ny, bool chainCharge) {
  int hits = 0;
  for (int i=0;i<numBots;i++) {
    if (bots[i].alive && bots[i].phaseInTicks <= 0 &&
        bots[i].pos.x == nx && bots[i].pos.y == ny) {
      // ALL skills deal exactly 1 damage — armor is answered by MORE
      // hits, not bigger ones. Comboing bots is the whole point.
      damageBot(i, 1, nx, ny);
      if (chainCharge) comboBump();
      hits++;
    }
  }
  if (hasKey && keyPos.x==nx && keyPos.y==ny) {
    hasKey=false; comboBump(); txCount++;
    if (chainCharge) { comboBump(); comboBump(); }   // dashed TX = 3 stacks total
    float fm=FRONTRUN_MULT[pasRank(SKILL_P_FRONT_RUN)];
    int kp=(int)(txBase()*comboMult*fm);
    score+=kp; if(score>(int)hi) hi=score;
    snakeLen=min(snakeLen+1,GRID*GRID-2);
    spawnFloater(nx,ny,kp,FLT_HASH);
    addParticles(nx,ny,C_GREEN,10,2.5f);
    hits++;
    if (txCount == TXS_PER_BLOCK) { strcpy(satMsg,"BLOCK SEALED"); satMsgT=60; }
  }
  if (hasShield && shieldPos.x==nx && shieldPos.y==ny) {
    hasShield=false;
    shieldStack = min(MAX_SHIELDS, shieldStack+1);
    shieldTTL = SHIELD_TTL;
    addParticles(nx,ny,C_PURPLE_C,10);
    if (chainCharge) comboBump();
    hits++;
  }
  if (hasSatoshi && satoshiPos.x==nx && satoshiPos.y==ny) {
    hasSatoshi=false;
    int sp=(int)(10.0f*txBase()*comboMult);
    score+=sp; if(score>(int)hi) hi=score;
    spawnFloater(nx,ny,sp,FLT_GOLD);
    addParticles(nx,ny,C_WHITE_C,16,3.0f);
    satBurstStart = cgNow(); satBurstX = nx; satBurstY = ny; fxSatoshi();
    satRushUntil = cgNow() + SAT_RUSH_MS;   // 11bq
    satWipe(nx, ny);                        // 11br
    if (chainCharge) comboBump();
    hits++;
  }
  if (hasBC && bcPos.x==nx && bcPos.y==ny) {
    hasBC=false;
    collectBlue(bcStage, nx, ny);
    if (chainCharge) comboBump();
    hits++;
  }
  if (hasOLPick && olPickPos.x==nx && olPickPos.y==ny) {
    hasOLPick=false;
    mineBlock(nx, ny);
    if (chainCharge) comboBump();
    hits++;
  }
  return hits;
}

