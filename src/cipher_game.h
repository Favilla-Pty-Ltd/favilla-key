// ── Additive blend: read existing pixel, ADD light on top ──
// This is how real glow/flame works — light adds, never blocks
// Result = clamp(existing + colour*alpha, 255)
// Direct buffer access (see cipherSprBuf). The previous version did two
// virtual readPixel/drawPixel round trips — and called drawPixel TWICE with
// the same arguments, so every glow pixel cost three library calls.
void addPixel(int x, int y, uint8_t r, uint8_t g, uint8_t b, float a) {
  if (x<0||x>=CIPHER_SPR_W||y<0||y>=CIPHER_SPR_H) return;
  // alpha as 8-bit fixed point; the per-pixel work is then all integer
  uint32_t aq = (uint32_t)(a * 256.0f); if (aq > 256) aq = 256;
  if (aq == 0) return;
  uint32_t ar = (r * aq) >> 8, ag = (g * aq) >> 8, ab = (b * aq) >> 8;
  uint16_t* buf = cipherSprBuf();
  if (buf) {
    uint16_t* p = buf + x + y * CIPHER_SPR_W;
    uint16_t c = cipherSwap16(*p);
    uint32_t er = ((c >> 11) & 0x1F) << 3;
    uint32_t eg = ((c >> 5)  & 0x3F) << 2;
    uint32_t eb = ((c)       & 0x1F) << 3;
    er += ar; if (er > 255) er = 255;
    eg += ag; if (eg > 255) eg = 255;
    eb += ab; if (eb > 255) eb = 255;
    *p = cipherSwap16((uint16_t)(((er & 0xF8) << 8) | ((eg & 0xFC) << 3) | (eb >> 3)));
    return;
  }
  uint16_t existing = spr.readPixel(x, y);
  uint8_t er = ((existing >> 11) & 0x1F) << 3;
  uint8_t eg = ((existing >> 5)  & 0x3F) << 2;
  uint8_t eb = ((existing)       & 0x1F) << 3;
  uint8_t nr = (uint8_t)min(255, (int)er + (int)ar);
  uint8_t ng = (uint8_t)min(255, (int)eg + (int)ag);
  uint8_t nb = (uint8_t)min(255, (int)eb + (int)ab);
  spr.drawPixel(x, y, cipherRgb(nr, ng, nb));
}
// Additive filled rectangle — each pixel gets light added
void addRect(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, float a) {
  for (int py=y; py<y+h; py++)
    for (int px=x; px<x+w; px++)
      addPixel(px, py, r, g, b, a);
}

// ── Icon blit — 4-bit alpha mask, ALPHA-BLENDED (not additive) so icons read
// as solid shapes on any backing. Mask format from tools/svg2a4.py: two
// pixels per byte, high nibble = left pixel, CIPHER_ICON_STRIDE bytes per row.
// `a` scales the whole icon (dim for unselected rows); colour is the caller's.
void cipherBlitA4(int x0, int y0, const uint8_t* mask, uint8_t r, uint8_t g, uint8_t b, float a) {
  uint32_t aq = (uint32_t)(a * 256.0f); if (aq > 256) aq = 256;
  uint16_t* buf = cipherSprBuf();
  for (int y = 0; y < CIPHER_ICON_PX; y++) {
    int py = y0 + y;
    if (py < 0 || py >= CIPHER_SPR_H) continue;
    const uint8_t* row = mask + y * CIPHER_ICON_STRIDE;
    for (int x = 0; x < CIPHER_ICON_PX; x++) {
      int px = x0 + x;
      if (px < 0 || px >= CIPHER_SPR_W) continue;
      uint8_t q = (x & 1) ? (row[x >> 1] & 0x0F) : (row[x >> 1] >> 4);
      if (!q) continue;
      uint32_t al = (q * 17 * aq) >> 8;          // 0..255
      if (al >= 250 && buf) {                      // fully opaque: straight write
        buf[px + py * CIPHER_SPR_W] = cipherSwap16(cipherRgb(r, g, b));
        continue;
      }
      uint32_t er, eg, eb;
      if (buf) {
        uint16_t c = cipherSwap16(buf[px + py * CIPHER_SPR_W]);
        er = ((c >> 11) & 0x1F) << 3; eg = ((c >> 5) & 0x3F) << 2; eb = (c & 0x1F) << 3;
      } else {
        uint16_t c = spr.readPixel(px, py);
        er = ((c >> 11) & 0x1F) << 3; eg = ((c >> 5) & 0x3F) << 2; eb = (c & 0x1F) << 3;
      }
      uint32_t nr = (er * (255 - al) + r * al) / 255;
      uint32_t ng = (eg * (255 - al) + g * al) / 255;
      uint32_t nb = (eb * (255 - al) + b * al) / 255;
      if (buf) buf[px + py * CIPHER_SPR_W] = cipherSwap16(cipherRgb((uint8_t)nr, (uint8_t)ng, (uint8_t)nb));
      else     spr.drawPixel(px, py, cipherRgb((uint8_t)nr, (uint8_t)ng, (uint8_t)nb));
    }
  }
}

