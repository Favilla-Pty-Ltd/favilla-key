// Additive filled circle — radial falloff for natural glow shape
// alpha at centre = a, falls to 0 at radius r. The sqrt per pixel stays —
// the falloff curve (1-d/r)^2 is the look, and with the buffer path the
// sqrt is no longer the expensive part of this loop.
void addCircleGlow(int cx, int cy, int r, uint8_t cr, uint8_t cg, uint8_t cb, float a) {
  if (r <= 0) return;
  int r2 = r*r;
  float invR = 1.0f / (float)r;
  for (int py=cy-r; py<=cy+r; py++) {
    if (py < 0 || py >= CIPHER_SPR_H) continue;
    int dy = py-cy;
    for (int px=cx-r; px<=cx+r; px++) {
      if (px < 0 || px >= CIPHER_SPR_W) continue;
      int dx = px-cx;
      int d2 = dx*dx+dy*dy;
      if (d2 > r2) continue;
      float falloff = 1.0f - sqrtf((float)d2)*invR;
      falloff = falloff*falloff; // quadratic falloff — more natural
      addPixel(px, py, cr, cg, cb, a*falloff);
    }
  }
}

// Additive rect glow with radial falloff from centre
void addRectGlow(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, float a, int spread) {
  if (spread <= 0) return;
  int cx=x+w/2, cy=y+h/2;
  int maxR=spread+max(w,h)/2;
  int s2 = spread*spread;
  float invS = 1.0f / (float)spread;
  for (int py=cy-maxR; py<=cy+maxR; py++) {
    if (py < 0 || py >= CIPHER_SPR_H) continue;
    int dy=max(0, max(y-py, py-(y+h)));
    for (int px=cx-maxR; px<=cx+maxR; px++) {
      if (px < 0 || px >= CIPHER_SPR_W) continue;
      // Distance from nearest rect edge
      int dx=max(0, max(x-px, px-(x+w)));
      int d2=dx*dx+dy*dy;
      if (d2>s2) continue;
      float falloff=1.0f-sqrtf((float)d2)*invS;
      falloff=falloff*falloff;
      addPixel(px,py,r,g,b,a*falloff);
    }
  }
}

bool isFree(int x, int y) {

  if (x<0||x>=GRID||y<0||y>=GRID) return false;
  for (int i=0;i<snakeLen;i++) if (snake[i].x==x && snake[i].y==y) return false;
  if (hasKey && keyPos.x==x && keyPos.y==y) return false;
  if (hasOLPick && olPickPos.x==x && olPickPos.y==y) return false;
  if (hasShield && shieldPos.x==x && shieldPos.y==y) return false;
  if (hasSatoshi && satoshiPos.x==x && satoshiPos.y==y) return false;
  if (hasBC && bcPos.x==x && bcPos.y==y) return false;
  for (int i=0;i<numBots;i++) if (bots[i].alive && bots[i].pos.x==x && bots[i].pos.y==y) return false;
  return true;
}

void freeCell(CipherPos& out) {
  // Try random spots
  for (int a=0; a<200; a++) {
    out.x=rng(GRID); out.y=rng(GRID);
    if (isFree(out.x, out.y)) return;
  }
  out.x=0; out.y=0;
}

void addParticles(int gx, int gy, uint16_t col, int n, float speed=2.5f) {
  float px = GX + gx*CS + CS/2;
  float py = GY + gy*CS + CS/2;
  for (int i=0; i<n && numParts<64; i++) {
    float a = (float)(random(628)) / 100.0f;
    float sp = speed*0.6f + (float)random(100)/100.0f * speed;
    parts[numParts++] = {
      px, py,
      cosf(a)*sp, sinf(a)*sp,
      1.0f, 0.03f + (float)random(40)/1000.0f,
      1.2f + (float)random(20)/10.0f,
      col
    };
  }
}

