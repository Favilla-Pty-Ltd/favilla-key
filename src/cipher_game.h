#define ZAP_COMBO_CAP 21   // combo still feeds the storm, but a boss takes >1 volley
void zapRelease() {
  if (!zapChargingSlot) return;
  int slot = zapChargingSlot;
  zapChargingSlot = 0;
  float cf = min(1.0f, (float)(cgNow()-zapChargeStart) / zapChargeMsNow());
  // base 3, charge worth up to +9 (3/6/9/12 tiers), and EVERY combo stack
  // is another bolt — uncapped. The chain IS the storm...
  int bolts = 3 + (int)(cf*9.01f) + min(combo, ZAP_COMBO_CAP);
  // ...and every bolt is PAID FOR. PROOF OF WORK discounts the per-bolt
  // price; if the wallet can't cover the full storm, fire what it can.
  long per100 = 0;   // 11bk: ZAP STORM's bolts are free
  long affordable = (per100 > 0) ? (cgWallet() * 100) / per100 : bolts;
  if (affordable < 1) { cipherWarn("NEED 1", 45); fxDenied(); return; }
  if ((long)bolts > affordable) bolts = (int)affordable;
  long zapCost = ((long)bolts * per100 + 99) / 100;   // round up
  cipherSpendEmbers(zapCost);
  runEmberDelta -= zapCost;
  spawnFloater(snake[0].x, snake[0].y, zapCost, FLT_EMBER_NEG);
  slotFired(slot, 0);
  int first = (bolts > 8) ? 8 : bolts;
  spawnZapRing(first);
  zapQueue = bolts - first;              // the rest ripple out as rings
  zapNextRing = cgNow() + 220;
  fxZapFire();
  snprintf(satMsg,sizeof(satMsg),"ZAP x%d",bolts); satMsgT=45;
}

