// Weekly board: same seed for everyone in the same UTC week (weeks from
// Mon 1 Jan 2024). 0 = clock not set -> practice on a random board.
uint32_t cgWeekIndex() {
  time_t now; time(&now);
  if ((long)now < 1700000000L) return 0;
  return (uint32_t)(((long)now - 1704067200L) / 604800L) + 1;
}
uint32_t cgWeekSeed(uint32_t wk) {
  uint32_t h = 0x811C9DC5u ^ 0x43495048u;            // "CIPH"
  for (int i = 0; i < 4; i++) { h ^= (wk >> (8 * i)) & 0xFF; h *= 16777619u; }
  return h ? h : 1;
}
