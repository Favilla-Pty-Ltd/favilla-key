// Calendar (ISO) week for display — the board itself is keyed by cgWeekIndex()
int cgIsoWeek() {
  time_t now; time(&now);
  if ((long)now < 1700000000L) return 0;
  struct tm t; gmtime_r(&now, &t);
  int wd = (t.tm_wday + 6) % 7;                 // Monday = 0
  int w = (t.tm_yday - wd + 10) / 7;
  if (w < 1) w = 52;
  if (w > 52) { int jan1 = (wd - t.tm_yday % 7 + 7) % 7; if (jan1 != 3 && !(jan1 == 2 && ((t.tm_year + 1900) % 4 == 0))) w = 1; }
  return w;
}
