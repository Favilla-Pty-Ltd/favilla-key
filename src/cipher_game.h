// ── DETERMINISTIC CORE (Phase 1, Oct 2026) ─────────────────────────────────
// Every gameplay timer reads cgNow(), a virtual clock that advances EXACTLY
// CIPHER_FRAME_MS per LOGIC STEP while playing (real time is banked and spent
// in whole steps — see cgAcc) and tracks real time on the menus,
// and every gameplay random draw comes from rng(), a seeded mulberry32 —
// the same generator the browser sim uses. A run is therefore reproducible
// from (seed, rules, input log): the basis for speed runs, signed events,
// replay verification and the server-checked web version. Visual-only
// randomness (particles, menu embers, shatter glyphs) stays on random() so a
// cosmetic can never change an outcome. millis() is kept ONLY for real-time
// I/O: frame pacing, piezo steps, relay/QR timeouts, the gamble reveal.
unsigned long cgClock    = 100000UL;   // non-zero so cooldowns start "ready"
unsigned long cgRealPrev = 0;
// Fixed-timestep accumulator (v2.1). Real time is banked in cgAcc while
// playing and spent in exact CIPHER_FRAME_MS logic steps, so the game runs at
// real speed even when a render frame overruns 33 ms (several steps, one
// draw), and stays deterministic: logic only ever sees whole 33 ms steps.
// v1/v2 advanced the clock one step per RENDERED frame, so any overrun slowed
// the whole game down (felt most at the slow 260 ms start).
unsigned long cgAcc = 0;
#define CG_MAX_STEPS 4                 // catch-up cap: below ~7 fps the game slows instead of jumping
static inline unsigned long cgNow() { return cgClock; }
uint32_t cgSeed = 1, cgRngState = 1;
uint32_t cgSeedOverride = 0;           // non-zero = next run uses this seed (events / speed runs)
static inline uint32_t cgRand32() {    // mulberry32 — bit-identical to the JS sim
  uint32_t a = (cgRngState += 0x6D2B79F5u);
  uint32_t t = (a ^ (a >> 15)) * (a | 1u);
  t = (t + ((t ^ (t >> 7)) * (t | 61u))) ^ t;
  return t ^ (t >> 14);
}
