// ── CipherBot spawning ───────────────────────────────────────────
int maxBotsForOL(int ol) {
  if (ol < 2) return 1;   // blocks 1–2: learn the board
  if (ol < 4) return 2;   // blocks 3–4: mid-game pressure begins
  if (ol < 6) return 3;   // blocks 5–6: speed floor reached, threats scale instead
  if (ol < 9) return 4;   // blocks 7–9
  return 5;               // endgame: full saturation
}

int rollBotTier() {
  int ol = overloads, r = rng(100);
  if (ol <= 1) return 1;
  if (ol <= 3) return (r < 75) ? 1 : 2;
  if (ol <= 5) return (r < 50) ? 1 : (r < 85 ? 2 : 3);
  if (ol <= 7) return (r < 30) ? 1 : (r < 75 ? 2 : 3);
  return (r < 15) ? 1 : (r < 55 ? 2 : 3);
}

void spawnBot(int id) {
  // Find existing slot for this id
  int slot = -1;
  for (int i=0; i<numBots; i++) {
    if (bots[i].id == id && !bots[i].alive) { slot=i; break; }
  }
  if (slot < 0) {
    if (numBots >= 5) return;
    slot = numBots++;
  }

  CipherPos p; freeCell(p);
  memset(&bots[slot], 0, sizeof(CipherBot));
  bots[slot].pos = p;
  bots[slot].id = id;
  bots[slot].alive = true;
  bots[slot].lastMove = cgNow();
  bots[slot].trailLen = 0;
  bots[slot].phaseInTicks = 18;  // ~1.2s phase-in at ~15 ticks/s
  int tier = rollBotTier();
  bots[slot].hp = bots[slot].maxHp = (uint8_t)tier;
}

void spawnHostiles() {
  int eligible[5], eCount=0;
  for (int i=0;i<5;i++) if (overloads >= BOT_UNLOCK[i]) eligible[eCount++]=i;
  int want = maxBotsForOL(overloads);
  int attempts=0;
  while (numBots < want && attempts < 30) {
    attempts++;
    if (eCount == 0) break;
    // Pick a bot id not already alive
    bool used[5]={};
    for (int i=0;i<numBots;i++) if (bots[i].alive) used[bots[i].id]=true;
    int pool[5], pCount=0;
    for (int i=0;i<eCount;i++) if (!used[eligible[i]]) pool[pCount++]=eligible[i];
    if (pCount==0) break;
    spawnBot(pool[rng(pCount)]);
  }
}

