#!/usr/bin/env python3
# Generates the multisig KAT vectors for the Favilla KEY harness using embit
# (independent implementation). Cosigner A is the KEY. Output: vectors/ms_vectors.h
from embit import bip32, bip39, script, psbt, transaction, descriptor, ec, hashes, base58, bech32
from embit.networks import NETWORKS
from embit.psbt import DerivationPath
import hashlib, io

NET = NETWORKS["main"]
MNEMS = [
 "abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about",
 "legal winner thank year wave sausage worth useful legal winner thank yellow",
 "letter advice cage absurd amount doctor acoustic avoid letter advice cage above",
]
PATH = "m/48h/0h/0h/2h"
roots, accts = [], []
for m in MNEMS:
    r = bip32.HDKey.from_seed(bip39.mnemonic_to_seed(m))
    roots.append(r); accts.append(r.derive(PATH))
fps = [r.my_fingerprint for r in roots]
xpubs = [a.to_public() for a in accts]

# sortedmulti descriptor (2 of 3)
keys = ",".join("[%s/48h/0h/0h/2h]%s/{0,1}/*" % (fps[i].hex(), xpubs[i].to_string()) for i in range(3))
desc = descriptor.Descriptor.from_string("wsh(sortedmulti(2,%s))" % keys)

def addr(change, idx):
    d = desc.derive(idx, branch_index=change)
    return d.script_pubkey().address(NET), d.script_pubkey().data, d.witness_script().data

# Coldcard multisig config (what Sparrow exports as "Keystone Multisig")
cc = "Name: KAT 2of3\nPolicy: 2 of 3\nDerivation: m/48'/0'/0'/2'\nFormat: P2WSH\n\n"
for i in range(3):
    cc += "%s: %s\n" % (fps[i].hex().upper(), xpubs[i].to_string())

# Build a PSBT: 2 inputs (0/0 and 0/5), outputs: recipient + change 1/3
_, spk00, ws00 = addr(0,0)
_, spk05, ws05 = addr(0,5)
_, spk13, ws13 = addr(1,3)
recip_spk = script.Script(bytes.fromhex("0014") + hashlib.sha256(b"recipient").digest()[:20])
vin = [transaction.TransactionInput(bytes.fromhex("aa"*32), 0), transaction.TransactionInput(bytes.fromhex("bb"*32), 3)]
vout = [transaction.TransactionOutput(150000, recip_spk), transaction.TransactionOutput(48000, script.Script(spk13))]
tx = transaction.Transaction(version=2, vin=vin, vout=vout, locktime=800000)
p = psbt.PSBT(tx)
for i,(spk,ws,c,idx,val) in enumerate([(spk00,ws00,0,0,100000),(spk05,ws05,0,5,100000)]):
    p.inputs[i].witness_utxo = transaction.TransactionOutput(val, script.Script(spk))
    p.inputs[i].witness_script = script.Script(ws)
    for k in range(3):
        pub = xpubs[k].derive([c,idx]).key
        p.inputs[i].bip32_derivations[pub] = DerivationPath(fps[k], [0x80000030,0x80000000,0x80000000,0x80000002,c,idx])
p.outputs[1].witness_script = script.Script(ws13)
for k in range(3):
    pub = xpubs[k].derive([1,3]).key
    p.outputs[1].bip32_derivations[pub] = DerivationPath(fps[k], [0x80000030,0x80000000,0x80000000,0x80000002,1,3])
for k in range(3):
    p.xpubs[xpubs[k]] = DerivationPath(fps[k], [0x80000030,0x80000000,0x80000000,0x80000002])
unsigned = p.serialize()

# Cosigner B signs first (so the KEY must pass through an existing partial sig)
pB = psbt.PSBT.parse(unsigned); pB.sign_with(roots[1])
with_b = pB.serialize()

# Expected: KEY (A) signs. The firmware's ecdsa_sign is plain RFC6979 low-S with
# NO low-R grinding, so switch embit's grinding off for cosigner A to get
# byte-identical signatures (both forms are valid; Sparrow accepts either).
_orig_sign = ec.PrivateKey.sign
ec.PrivateKey.sign = lambda self, h, grind=True: _orig_sign(self, h, grind=False)
pA = psbt.PSBT.parse(with_b); pA.sign_with(roots[0])
ec.PrivateKey.sign = _orig_sign
sigsA = []
for i in range(2):
    pub = xpubs[0].derive([0,[0,5][i]]).key
    sigsA.append(pA.inputs[i].partial_sigs[pub])
sighashes = [pA.sighash(i) for i in range(2)]

# Also a single-sig BIP-84 vector for the mixed-refusal test: KEY's m/84'/0'/0'/0/0
acct84 = roots[0].derive("m/84h/0h/0h").to_public()
pub84 = acct84.derive([0,0]).key
spk84 = script.p2wpkh(pub84).data

def carr(name, b):
    return "static const uint8_t %s[%d] = {%s};\n" % (name, len(b), ",".join("0x%02x"%x for x in b))
out = "// AUTO-GENERATED by gen_vectors.py (embit). Do not hand-edit.\n#pragma once\n#include <stdint.h>\n"
out += 'static const char MS_KAT_CONFIG[] = %s;\n' % ('"' + cc.replace("\n","\\n") + '"')
for i in range(3):
    out += carr("MS_KAT_FP%d"%i, fps[i])
    out += carr("MS_KAT_XPUB78_%d"%i, xpubs[i].serialize())
    out += 'static const char MS_KAT_XPUBSTR_%d[] = "%s";\n' % (i, xpubs[i].to_string())
out += carr("MS_KAT_SEED_A", bip39.mnemonic_to_seed(MNEMS[0]))
for c,idx in [(0,0),(0,5),(1,3)]:
    a, spk, ws = addr(c,idx)
    out += 'static const char MS_KAT_ADDR_%d_%d[] = "%s";\n' % (c,idx,a)
    out += carr("MS_KAT_SPK_%d_%d"%(c,idx), spk)
    out += carr("MS_KAT_WS_%d_%d"%(c,idx), ws)
out += carr("MS_KAT_PSBT_UNSIGNED", unsigned)
out += carr("MS_KAT_PSBT_WITH_B", with_b)
out += carr("MS_KAT_PSBT_AB", pA.serialize())
for i in range(2):
    out += carr("MS_KAT_SIGHASH_%d"%i, sighashes[i])
    out += carr("MS_KAT_SIG_A_%d"%i, sigsA[i])
out += carr("MS_KAT_PUBA_0_0", xpubs[0].derive([0,0]).key.serialize())
out += carr("MS_KAT_PUBA_0_5", xpubs[0].derive([0,5]).key.serialize())
out += carr("MS_KAT_SPK84_0_0", spk84)
out += carr("MS_KAT_PUB84_0_0", pub84.serialize())
out += 'static const char MS_KAT_KEYEXPR_A[] = "[%s/48h/0h/0h/2h]%s";\n' % (fps[0].hex(), xpubs[0].to_string())
open("vectors/ms_vectors.h","w").write(out)
open("vectors/unsigned.psbt","wb").write(unsigned)
open("vectors/with_b.psbt","wb").write(with_b)
print("fps", [f.hex() for f in fps]); print("addr 0/0", addr(0,0)[0]); print("psbt bytes", len(unsigned), len(with_b))
print("sigA0 len", len(sigsA[0]))
