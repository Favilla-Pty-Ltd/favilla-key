#!/usr/bin/env python3
"""make_anchor.py — build include/ember_anchor.h, the header-clock checkpoint
compiled into a G0 image. 28 Oct 2026.

The anchor is the G0's root of trust for time: nothing before it is ever
accepted, and everything after it must be mined on top of it. Make a fresh
one for every G0 image, from your own node:

  1. Pick the anchor height A (a recent block, at least 100 deep).
  2. Let S = A - (A % 2016), the first block of A's difficulty period.
  3. Dump every header from S to A, one raw hex header per line:
       for h in range(S, A+1): bitcoin-cli getblockheader $(bitcoin-cli getblockhash h) false
  4. python tools/make_anchor.py --start S headers.txt > include/ember_anchor.h

The tool re-checks the whole range itself (links, PoW, constant nBits inside
the period, median-time-past) so a bad dump cannot become an anchor.
Bench only: a single header at a period start (S == A) is accepted with the
ten earlier timestamps padded with 0, which weakens MTP for the first few
blocks after the anchor and nothing else. Marked BENCH in the output.
"""
import hashlib, sys, argparse, datetime
d = lambda b: hashlib.sha256(hashlib.sha256(b).digest()).digest()
le = lambda b, o: int.from_bytes(b[o:o+4], 'little')
def target(bits):
    n, w = bits >> 24, bits & 0x7fffff
    assert not (bits & 0x800000), 'negative nBits'
    return w >> 8*(3-n) if n <= 3 else w << 8*(n-3)
ap = argparse.ArgumentParser(); ap.add_argument('--start', type=int, required=True); ap.add_argument('file')
a = ap.parse_args()
H = [bytes.fromhex(l.strip()) for l in open(a.file) if l.strip()]
assert all(len(h) == 80 for h in H), 'every line must be one 80-byte header in hex'
S = a.start; A = S + len(H) - 1
assert S % 2016 == 0, '--start must be the first block of a difficulty period (multiple of 2016)'
assert A - S < 2016, 'range runs past the period'
limit = (1 << 224) - 1
for i, h in enumerate(H):
    hv = int.from_bytes(d(h), 'little'); t = target(le(h, 72))
    assert 0 < t <= limit and hv <= t, 'PoW fails at %d' % (S + i)
    assert le(h, 72) == le(H[0], 72), 'nBits changes inside the period at %d' % (S + i)
    assert le(h, 0) >= 4, 'version below 4 at %d' % (S + i)
    if i:
        assert h[4:36] == d(H[i-1]), 'link broken at %d' % (S + i)
        prev = sorted(le(x, 68) for x in H[max(0, i-11):i])
        if i >= 11: assert le(h, 68) > prev[len(prev)//2], 'MTP fails at %d' % (S + i)
times = [le(x, 68) for x in H[-11:]]
bench = len(times) < 11
if bench: times = [0] * (11 - len(times)) + times
ah = d(H[-1])
c = lambda b: ', '.join('0x%02x' % x for x in b)
when = datetime.datetime.fromtimestamp(le(H[-1], 68), datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
src = hashlib.sha256(open(a.file, 'rb').read()).hexdigest()
print('/* ember_anchor.h - generated by tools/make_anchor.py, do not edit.')
print(' * Anchor: height %d, block %s, %s' % (A, ah[::-1].hex(), when))
print(' * Input: %d headers %d..%d, sha256 of input file %s' % (len(H), S, A, src))
if bench: print(' * BENCH ANCHOR: fewer than 11 headers given; earlier timestamps padded with 0.')
print(' */\n#pragma once\n#include "ember_hdr.h"')
print('#define EMBER_ANCHOR_HEIGHT %du' % A)
if bench: print('#define EMBER_ANCHOR_BENCH 1')
print('static const eh_anchor_t EMBER_ANCHOR = {')
print('    .height = %du,' % A)
print('    .hash = { %s },' % c(ah))
print('    .bits = 0x%08xu,' % le(H[-1], 72))
print('    .pstart = %du,' % le(H[0], 68))
print('    .ntimes = 11,')
print('    .times = { %s },' % ', '.join('%du' % t for t in times))
print('};')
