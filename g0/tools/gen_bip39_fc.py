#!/usr/bin/env python3
"""Front-coded BIP-39 word list for the G0 (6 Nov 2026, size work for the next
G0 version). Reads the words out of src/bip39_words.c (the audited table, so
both encodings come from one source) and writes next/bip39_fc_data.h.

Per word, MSB first: 3 bits prefix length shared with the previous word (0..7),
4 bits suffix length (0..15), then 5 bits per suffix letter (a=0 .. z=25)."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "tests/ref/bip39_words_v15.c").read_text()
blob = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', src.split("BIP39_BLOB[] =")[1].split("BIP39_OFF")[0]))
words = blob.split("\\0")[:2048]
assert len(words) == 2048 and all(re.fullmatch(r"[a-z]{3,8}", w) for w in words)
bits, prev = [], ""
def put(v, n):
    for i in range(n - 1, -1, -1): bits.append((v >> i) & 1)
maxsuf = 0
for w in words:
    p = 0
    while p < min(len(w), len(prev), 7) and w[p] == prev[p]: p += 1
    put(p, 3); put(len(w) - p, 4); maxsuf = max(maxsuf, len(w) - p)
    for ch in w[p:]: put(ord(ch) - 97, 5)
    prev = w
while len(bits) % 8: bits.append(0)
data = bytes(int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))
out = ["/* Generated by tools/gen_bip39_fc.py from tests/ref/bip39_words_v15.c. Do not edit. */",
       "#pragma once", f"#define BIP39_FC_LEN {len(data)}",
       "static const uint8_t BIP39_FC[BIP39_FC_LEN] = {"]
for i in range(0, len(data), 24):
    out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
out.append("};")
(root / "src/bip39_fc_data.h").write_text("\n".join(out) + "\n")
print(f"{len(words)} words, {len(data)} bytes (was 13117 + 4096), longest suffix {maxsuf}")
