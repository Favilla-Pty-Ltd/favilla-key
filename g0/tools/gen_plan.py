# Independent model of the Emberwill chain (r7 + the 28 Oct decisions) in
# Python/embit. Emits random plans as EMBER_SET wire bytes plus every key, and
# the expected unsigned transactions (no-witness bytes) and txids.
import random, sys, struct
from embit import ec, script
from embit.transaction import Transaction, TransactionInput, TransactionOutput
out = sys.argv[1]
rng = random.Random(2810)
AFTERGLOW, DUST = 1008, 546
def rspk():
    k = rng.randrange(5); h = rng.randbytes
    return [b'\x00\x14' + h(20), b'\x00\x20' + h(32), b'\x51\x20' + h(32), b'\x76\xa9\x14' + h(20) + b'\x88\xac', b'\xa9\x14' + h(20) + b'\x87'][k]
def vsize_max(tx):
    base = len(Transaction(version=tx.version, vin=[TransactionInput(i.txid, i.vout, sequence=i.sequence) for i in tx.vin], vout=tx.vout, locktime=tx.locktime).serialize())
    wit = 2 + len(tx.vin) * (1 + 1 + 73 + 1 + 33)
    return (base * 4 + wit + 3) // 4
def p2wpkh(k): return script.p2wpkh(k.get_public_key())
def plan():
    nc, nh, nl = rng.randint(1, 3), rng.randint(1, 6), rng.randint(1, 8)
    coins = [(rng.randbytes(32), rng.randrange(8), rng.randrange(2_000_000, 500_000_000), rng.randrange(2), rng.randrange(1000), ec.PrivateKey(rng.randbytes(32))) for _ in range(nc)]
    cuts = sorted(rng.sample(range(1, 10000), nh - 1)); bps = [b - a for a, b in zip([0] + cuts, cuts + [10000])]
    heirs = [(rspk(), bp) for bp in bps]
    ex = rspk(); quiet = rng.choice([4032, 12960, 13140, 26280, 105120]); refi = rng.randrange(100)
    cr = sorted(rng.sample(range(1, 200), 3)); rr = rng.randrange(1, 60); bump = rng.randrange(546, 5000)
    refk = [ec.PrivateKey(rng.randbytes(32)) for _ in range(nl)]
    tip = rng.randrange(870000, 1000000)
    return nc, nh, nl, coins, heirs, ex, quiet, refi, cr, rr, bump, refk, tip
def wire(p):
    nc, nh, nl, coins, heirs, ex, quiet, refi, cr, rr, bump, refk, tip = p
    b = bytes([nc, nh, nl, 0])
    for i in range(3):
        if i < nc: t, v, a, ch, ix, k = coins[i]; b += t + struct.pack('<IQII', v, a, ch, ix)
        else: b += bytes(52)
    for i in range(6):
        b += (heirs[i][0].ljust(34, b'\0') + struct.pack('<H', heirs[i][1])) if i < nh else bytes(36)
    b += ex.ljust(34, b'\0') + struct.pack('<IIHHHHI', quiet, refi, *cr, rr, bump)
    assert len(b) == 430; return b
def X(p, i): return p[12] + p[6] + AFTERGLOW + i * p[6]
def chain(p):
    nc, nh, nl, coins, heirs, ex, quiet, refi, cr, rr, bump, refk, tip = p
    txs = []
    def C(inputs, link, v):
        vout = [TransactionOutput(0, script.Script(s)) for s, _ in heirs] + [TransactionOutput(bump, script.Script(ex))]
        tx = Transaction(version=2, vin=[TransactionInput(t, vo, sequence=0xfffffffd) for t, vo, a in inputs], vout=vout, locktime=X(p, link))
        fee = cr[v] * vsize_max(tx); avail = sum(a for _, _, a in inputs) - fee - bump
        amts = [avail * bp // 10000 for _, bp in heirs]; amts[0] += avail - sum(amts)
        for o, a in zip(tx.vout, amts): o.value = a
        assert all(a >= DUST for a in amts); return tx
    cin = [(t[::-1], v, a) for t, v, a, *_ in coins]   # embit TransactionInput wants display order
    for v in range(3): txs.append(('C', 0, v, C(cin, 0, v)))
    prev = cin
    for i in range(1, nl + 1):
        r = Transaction(version=2, vin=[TransactionInput(t, vo, sequence=0xfffffffd) for t, vo, a in prev],
                        vout=[TransactionOutput(0, p2wpkh(refk[i - 1]))], locktime=X(p, i - 1) - quiet // 2)
        r.vout[0].value = sum(a for _, _, a in prev) - rr * vsize_max(r); assert r.vout[0].value >= DUST
        txs.append(('R', i, 0, r))
        prev = [(r.txid(), 0, r.vout[0].value)]
        for v in range(3): txs.append(('C', i, v, C(prev, i, v)))
    return txs
c = lambda b: '{' + ','.join('0x%02x' % x for x in b) + '}'
L = ['/* generated by tools/gen_plan.py (embit model) — do not edit */', '#pragma once', '#include <stdint.h>',
     'typedef struct { uint8_t wire[430]; uint32_t tip; uint8_t cpriv[3][32]; uint8_t rpriv[8][32]; uint8_t ntx; uint32_t off[35]; uint16_t len[35]; uint8_t txid[35][32]; } plan_vec_t;']
blobs = bytearray(); P = []
for n in range(40):
    p = plan(); txs = chain(p)
    offs, lens, ids = [], [], []
    for kind, link, v, tx in txs:
        raw = tx.serialize(); offs.append(len(blobs)); lens.append(len(raw)); blobs += raw; ids.append(tx.txid()[::-1])
    P.append((wire(p), p[12], [k.secret for *_, k in p[3]] + [bytes(32)] * (3 - p[0]), [k.secret for k in p[11]] + [bytes(32)] * (8 - p[2]), len(txs), offs, lens, ids))
L.append('static const uint8_t PLAN_BLOBS[] = %s;' % c(blobs))
L.append('static const plan_vec_t PLANS[] = {')
for w, tip, cp, rp, n, offs, lens, ids in P:
    pad = lambda a, z: a + [z] * (35 - len(a))
    L.append('{%s,%du,{%s},{%s},%d,{%s},{%s},{%s}},' % (c(w), tip, ','.join(c(x) for x in cp), ','.join(c(x) for x in rp), n,
             ','.join(map(str, pad(offs, 0))), ','.join(map(str, pad(lens, 0))), ','.join(c(x) for x in pad(ids, bytes(32)))))
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n'); print(len(P), 'plans', len(blobs), 'bytes of txs')
