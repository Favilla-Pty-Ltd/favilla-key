# Nostr event vectors for src/ember_life.c, signed with embit (BIP-340).
import json, hashlib, random, sys
from embit import ec
out = sys.argv[1]; rng = random.Random(28)
owner = ec.PrivateKey(rng.randbytes(32)); other = ec.PrivateKey(rng.randbytes(32))
ox = owner.xonly()
def ser(pub, created, kind, tags, content):
    return json.dumps([0, pub, created, kind, tags, content], separators=(',', ':'), ensure_ascii=False).encode()
def sign(k, s): return k.schnorr_sign(hashlib.sha256(s).digest()).serialize()
V = []   # (ser, sig, want, created, kind, block)
words = ['gm', 'bitcoin', 'ünïcödé ✓', 'quote " and \\ backslash', 'line\nbreak', 'emoji 🔥', '']
for i in range(60):
    kind = rng.choice([1, 1, 1, 30023, 0, 3])
    tags = [] if rng.random() < .5 else [['e', rng.randbytes(32).hex()], ['p', rng.randbytes(32).hex(), 'wss://relay.example']]
    content = ' '.join(rng.choice(words) for _ in range(rng.randint(0, 20)))
    if kind == 0: content = json.dumps({'name': 'owner', 'about': rng.choice(words)})
    c = rng.randrange(1700000000, 1800000000)
    s = ser(ox.hex(), c, kind, tags, content); V.append((s, sign(owner, s), 1, c, kind, b''))
blocks = [rng.randbytes(32) for _ in range(10)]
for b in blocks:
    c = rng.randrange(1700000000, 1800000000)
    s = ser(ox.hex(), c, 8333, [], b[::-1].hex()); V.append((s, sign(owner, s), 2, c, 8333, b))
# refusals
s = ser(ox.hex(), 1760000000, 1, [], 'hi'); g = sign(owner, s)
V.append((s, sign(other, s), -3, 0, 0, b''))                                    # wrong signer, owner pubkey in event
s2 = ser(other.xonly().hex(), 1760000000, 1, [], 'hi'); V.append((s2, sign(other, s2), -2, 0, 0, b''))  # someone else's event
bad = bytearray(g); bad[5] ^= 1; V.append((s, bytes(bad), -3, 0, 0, b''))
s3 = ser(ox.hex(), 1760000000, 1, [], 'hj'); V.append((s3, g, -3, 0, 0, b''))   # content changed after signing
for k in [7, 9734, 4, 1984, 24133, 10002]:
    s = ser(ox.hex(), 1760000000, k, [], 'x'); V.append((s, sign(owner, s), -4, 0, 0, b''))
up = ser(ox.hex().upper(), 1760000000, 1, [], 'x'); V.append((up, sign(owner, up), -2, 0, 0, b''))
lead = ('[0,"%s",01760000000,1,[],"x"]' % ox.hex()).encode(); V.append((lead, sign(owner, lead), -1, 0, 0, b''))
long_ = ('[0,"%s",17600000000,1,[],"x"]' % ox.hex()).encode(); V.append((long_, sign(owner, long_), -1, 0, 0, b''))
sp = ('[0, "%s",1760000000,1,[],"x"]' % ox.hex()).encode(); V.append((sp, sign(owner, sp), -1, 0, 0, b''))
pt = ser(ox.hex(), 1760000000, 8333, [['e', 'x']], blocks[0][::-1].hex()); V.append((pt, sign(owner, pt), -1, 0, 0, b''))   # pulse with tags
pc = ser(ox.hex(), 1760000000, 8333, [], blocks[0][::-1].hex() + 'x'); V.append((pc, sign(owner, pc), -1, 0, 0, b''))
pu = ser(ox.hex(), 1760000000, 8333, [], blocks[0][::-1].hex().upper()); V.append((pu, sign(owner, pu), -1, 0, 0, b''))
big = ser(ox.hex(), 1760000000, 1, [], 'a' * 2100); V.append((big, sign(owner, big), -6, 0, 0, b''))
c = lambda b: '{' + ','.join('0x%02x' % x for x in b) + '}'
L = ['/* generated by tools/gen_life.py (embit BIP-340) — do not edit */', '#pragma once', '#include <stdint.h>',
     'static const uint8_t LIFE_OWNER[32] = %s;' % c(ox), 'static const uint8_t LIFE_OWNER_SK[32] = %s;' % c(owner.secret),
     'typedef struct { uint16_t len; const char *ser; uint8_t sig[64]; int want; uint32_t created, kind; uint8_t block[32]; } life_vec_t;',
     'static const life_vec_t LIFE[] = {']
def cstr(b): return '"' + ''.join('\\x%02x' % x for x in b) + '"'
for s, g, w, cr, k, b in V:
    L.append('{%d,%s,%s,%d,%du,%du,%s},' % (len(s), cstr(s), c(g), w, cr, k, c(b.ljust(32, b'\0'))))
L.append('};'); open(out, 'w').write('\n'.join(L) + '\n'); print(len(V), 'events')
