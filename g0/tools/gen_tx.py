# Reference vectors for src/ember_tx.c, built with embit (independent library):
# random Emberwill-shaped transactions (1-3 P2WPKH inputs, 1-7 standard
# outputs), signed by embit, with expected witness serialisation, txid and
# BIP-143 sighash per input. Plus the BIP-143 native P2WPKH sighash KAT.
import random, sys
from embit import ec, script
from embit.transaction import Transaction, TransactionInput, TransactionOutput, SIGHASH
out = sys.argv[1]  # e.g. tests/data/tx_vectors.h
rng = random.Random(281026)
c = lambda b: '{' + ','.join('0x%02x' % x for x in b) + '}'
def rspk():
    k = rng.randrange(5); h = rng.randbytes
    if k == 0: return b'\x00\x14' + h(20)
    if k == 1: return b'\x00\x20' + h(32)
    if k == 2: return b'\x51\x20' + h(32)
    if k == 3: return b'\x76\xa9\x14' + h(20) + b'\x88\xac'
    return b'\xa9\x14' + h(20) + b'\x87'
V = []
for n in range(300):
    keys = [ec.PrivateKey(rng.randbytes(32)) for _ in range(rng.randint(1, 3))]
    ins = [(rng.randbytes(32), rng.randrange(0, 5) if rng.random() < .8 else rng.randrange(2**32), rng.randrange(546, 2**40), k) for k in keys]
    outs = [(rng.randrange(0, 2**40), rspk()) for _ in range(rng.randint(1, 7))]
    lock = rng.choice([0, rng.randrange(1, 500000000), rng.randrange(800000, 1200000)])
    seq = 0xFFFFFFFD
    tx = Transaction(version=2, vin=[TransactionInput(t[::-1], v, sequence=seq) for t, v, a, k in ins],
                     vout=[TransactionOutput(a, script.Script(s)) for a, s in outs], locktime=lock)
    shs = []
    for i, (t, v, a, k) in enumerate(ins):
        sh = tx.sighash_segwit(i, script.p2pkh(k.get_public_key()), a); shs.append(sh)
        sig = k.sign(sh).serialize() + bytes([SIGHASH.ALL])
        tx.vin[i].witness = script.Witness([sig, k.get_public_key().sec()])
    V.append((ins, outs, lock, tx.serialize(), tx.txid()[::-1], shs, [w.witness.items[0] for w in tx.vin]))
L = ['/* generated by tools/gen_tx.py with embit — do not edit */', '#pragma once', '#include <stdint.h>',
     'typedef struct { uint8_t txid[32]; uint32_t vout; uint64_t amount; uint8_t pub[33]; uint8_t sig[73]; uint8_t siglen; uint8_t sighash[32]; } txv_in_t;',
     'typedef struct { uint64_t amount; uint8_t spk[34]; uint8_t spklen; } txv_out_t;',
     'typedef struct { uint8_t nin, nout; uint32_t lock; txv_in_t in[3]; txv_out_t out[7]; uint16_t rawlen; uint8_t raw[1100]; uint8_t txid[32]; } txv_t;',
     'static const txv_t TXV[] = {']
for ins, outs, lock, raw, txid, shs, sigs in V:
    assert len(raw) <= 1100
    si = ','.join('{%s,%du,%du,%s,%s,%d,%s}' % (c(t), v, a, c(k.get_public_key().sec()), c(s + bytes(73 - len(s))), len(s), c(sh)) for (t, v, a, k), s, sh in zip(ins, sigs, shs))
    so = ','.join('{%du,%s,%d}' % (a, c(s + bytes(34 - len(s))), len(s)) for a, s in outs)
    L.append('{%d,%d,%du,{%s},{%s},%d,%s,%s},' % (len(ins), len(outs), lock, si, so, len(raw), c(raw), c(txid)))
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n'); print(len(V), 'tx vectors')
