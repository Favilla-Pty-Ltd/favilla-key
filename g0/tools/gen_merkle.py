# Merkle branch vectors for the G0 check, built independently in Python:
#  - real: every tx of every multi-tx block in bitcoinj's early-mainnet block file,
#    txids computed from the raw transactions, root checked against the header
#  - synthetic: trees of 1..300 leaves built Core's way (odd levels duplicate the last)
import hashlib, random, sys
blkfile, out = sys.argv[1], sys.argv[2]
d = lambda b: hashlib.sha256(hashlib.sha256(b).digest()).digest()
def varint(b, o):
    x = b[o]
    if x < 0xfd: return x, o + 1
    n = {0xfd: 2, 0xfe: 4, 0xff: 8}[x]; return int.from_bytes(b[o+1:o+1+n], 'little'), o + 1 + n
def tx_end(b, o):
    s = o + 4; n, s = varint(b, s)
    for _ in range(n): s += 36; l, s = varint(b, s); s += l + 4
    n, s = varint(b, s)
    for _ in range(n): s += 8; l, s = varint(b, s); s += l
    return s + 4
def levels(leaves):
    L = [leaves[:]]
    while len(L[-1]) > 1:
        cur = L[-1][:]
        if len(cur) % 2: cur.append(cur[-1])
        L.append([d(cur[i] + cur[i+1]) for i in range(0, len(cur), 2)])
    return L
def branch(L, idx):
    out = []
    for lv in L[:-1]:
        sib = idx ^ 1
        out.append(lv[sib] if sib < len(lv) else lv[idx]); idx >>= 1
    return out
V = []
b = open(blkfile, 'rb').read(); o = 0; h = 0; real = 0
while o + 8 <= len(b):
    sz = int.from_bytes(b[o+4:o+8], 'little'); blk = b[o+8:o+8+sz]; o += 8 + sz
    if len(blk) < sz: break
    ntx, p = varint(blk, 80)
    if ntx > 1:
        ids = []
        for _ in range(ntx): e = tx_end(blk, p); ids.append(d(blk[p:e])); p = e
        L = levels(ids); assert L[-1][0] == blk[36:68], h
        for i in range(ntx): V.append((ids[i], i, branch(L, i), blk[36:68], 1)); real += 1
    h += 1
rng = random.Random(28102026)
for n in list(range(1, 34)) + [64, 65, 127, 128, 129, 255, 300, 1000, 4097]:
    ids = [rng.randbytes(32) for _ in range(n)]; L = levels(ids); root = L[-1][0]
    idxs = range(n) if n <= 33 else rng.sample(range(n), 6) + [n - 1]
    for i in idxs:
        br = branch(L, i); V.append((ids[i], i, br, root, 1))
        if n > 1:   # wrong leaf, wrong position (where it differs), truncated branch
            V.append((rng.randbytes(32), i, br, root, 0))
            j = i ^ 1
            if j < n and ids[j] != ids[i] and br[0] != ids[i]: V.append((ids[i], j, br, root, 0))
            V.append((ids[i], i & ((1 << (len(br)-1)) - 1), br[:-1], root, 0))
assert max(len(v[2]) for v in V) <= 20
c = lambda x: '{' + ','.join('0x%02x' % y for y in x) + '}'
L = ['/* generated by tools/gen_merkle.py — do not edit */', '#pragma once', '#include <stdint.h>',
     'typedef struct { uint8_t leaf[32]; uint32_t index; uint8_t depth; uint8_t nodes[20][32]; uint8_t root[32]; uint8_t ok; } mk_gen_t;',
     '#define MK_GEN_REAL %d' % real, 'static const mk_gen_t MK_GEN[] = {']
for leaf, i, br, root, ok in V:
    L.append('{%s,%du,%d,{%s},%s,%d},' % (c(leaf), i, len(br), ','.join(c(x) for x in br) or '{0}', c(root), ok))
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
print(real, 'real', len(V), 'total')
