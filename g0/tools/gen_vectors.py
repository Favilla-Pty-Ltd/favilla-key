# Builds tests/data/ember_vectors.h from public mainnet test data (summa-tx
# relays + bitcoin-spv) and Bitcoin Core's pow_tests.cpp values.
import json, hashlib, sys
ext, out = sys.argv[1], sys.argv[2]
R = json.load(open(ext + '/relays/testVectors.json'))
S = json.load(open(ext + '/bitcoin-spv/testVectors.json'))
P = json.load(open(ext + '/bitcoin-spv/testProofs.json'))
hx = lambda s: bytes.fromhex(s[2:] if s.startswith('0x') else s)
dsha = lambda b: hashlib.sha256(hashlib.sha256(b).digest()).digest()
le32 = lambda b, o: int.from_bytes(b[o:o+4], 'little')
def carr(b): return '{' + ','.join('0x%02x' % x for x in b) + '}'
L = ['/* generated by tools/gen_vectors.py — mainnet data, do not edit */', '#pragma once', '#include <stdint.h>', '']
# retarget vectors: first_time, last_time, last_bits, expected next bits, height of new period
rt = []
for v in S['retargetAlgorithm']:
    a, b, c = v['input']
    if c['height'] % 2016 or b['height'] != c['height'] - 1 or a['height'] != c['height'] - 2016: continue
    bits = lambda s: int.from_bytes(hx(s), 'little')
    rt.append((a['timestamp'], b['timestamp'], bits(b['nbits']), bits(c['nbits']), c['height'], 'bitcoin-spv'))
for v in R['header']['validateDifficultyChange']:
    if v['output'] != 0: continue
    s, an, h = hx(v['prevEpochStart']['raw']), hx(v['anchor']['raw']), hx(v['headers'][0]['raw'])
    rt.append((le32(s,68), le32(an,68), le32(an,72), le32(h,72), v['headers'][0]['height'], 'relays'))
# Bitcoin Core src/test/pow_tests.cpp (mainnet params)
rt += [(1261130161, 1262152739, 0x1d00ffff, 0x1d00d86a, 32256, 'core get_next_work'),
       (1231006505, 1233061996, 0x1d00ffff, 0x1d00ffff, 2016, 'core pow_limit'),
       (1279008237, 1279297671, 0x1c05a3f4, 0x1c0168fd, 68544, 'core lower_limit_actual'),
       (1263163443, 1269211443, 0x1c387f6f, 0x1d00e1fd, 46368, 'core upper_limit_actual'),
       (1279297671 - 302400, 1279297671, 0x1c05a3f5, 0x1c0168fd, 0, 'core mantissa_not_x4'),
       (1279297671, 1279008237, 0x1c05a3f4, 0x1c0168fd, 0, 'core negative_timespan')]
L.append('typedef struct { uint32_t first, last, bits, next, height; const char *src; } rt_vec_t;')
L.append('static const rt_vec_t RT_VECS[] = {')
for r in rt: L.append('  {%du,%du,0x%08xu,0x%08xu,%du,"%s"},' % r)
L.append('};\n')

def hdrs(name, lst):
    L.append('static const uint8_t %s[][80] = {' % name)
    for h in lst: L.append('  ' + carr(hx(h['raw'])) + ',')
    L.append('};')
# chain A: crosses the 437472 retarget, with a real stale block at 437478
A = R['chain']['isMostRecentCommonAncestor']
chainA = A['preRetargetChain'] + A['postRetargetChain']
hs = [A['genesis']['height']] + [h['height'] for h in chainA]
assert hs == list(range(hs[0], hs[0] + len(hs))), hs
hdrs('A_ANCHOR', [A['genesis']]); hdrs('A_CHAIN', chainA); hdrs('A_STALE', [A['orphan']])
L.append('#define A_HEIGHT %du\n#define A_PSTART %du\n#define A_STALE_HEIGHT %du\n' % (A['genesis']['height'], le32(hx(A['oldPeriodStart']['raw']),68), A['orphan']['height']))
# chain B: 562621.. with two competing blocks at 562630
B = R['chain']['heaviestFromAncestor']
hs = [B['genesis']['height']] + [h['height'] for h in B['headers']]
assert hs == list(range(hs[0], hs[0] + len(hs))), hs
hdrs('B_ANCHOR', [B['genesis']]); hdrs('B_CHAIN', B['headers']); hdrs('B_STALE', [B['orphan'], B['badHeader']])
L.append('#define B_HEIGHT %du\n#define B_STALE_HEIGHT %du\n' % (B['genesis']['height'], B['orphan']['height']))
# chain C: retarget at 306432
C = [v for v in R['header']['validateDifficultyChange'] if v['output'] == 0][0]
hdrs('C_ANCHOR', [C['anchor']]); hdrs('C_CHAIN', C['headers'])
L.append('#define C_HEIGHT %du\n#define C_PSTART %du\n' % (C['anchor']['height'], le32(hx(C['prevEpochStart']['raw']),68)))
# Merkle proofs against real headers
pr = []
def addproof(p, src):
    nodes = hx(p['intermediate_nodes']); hdr = hx(p['confirming_header']['raw']); tx = hx(p['tx_id'])
    pr.append((tx, p['index'], nodes, hdr, src))
for s in P['valid']: addproof(json.loads(s) if isinstance(s, str) else s, 'bitcoin-spv valid')
for v in R['validator']['validateProof']: addproof(v['proof'], 'relays validateProof')
L.append('typedef struct { uint8_t txid[32]; uint32_t index; uint8_t depth; uint8_t nodes[20][32]; uint8_t hdr[80]; const char *src; } mk_vec_t;')
L.append('static const mk_vec_t MK_VECS[] = {')
for tx, idx, nodes, hdr, src in pr:
    n = len(nodes)//32
    L.append('  {%s,%du,%d,{%s},%s,"%s"},' % (carr(tx), idx, n, ','.join(carr(nodes[i*32:i*32+32]) for i in range(n)), carr(hdr), src))
L.append('};')
# bitcoin-spv verifyHash256Merkle: txid || nodes || root, index -> bool
L.append('typedef struct { uint8_t len; uint8_t buf[22*32]; uint32_t index; int ok; } mk_raw_t;')
L.append('static const mk_raw_t MK_RAW[] = {')
for v in S['verifyHash256Merkle']:
    b = hx(v['input']['proof'])
    if len(b) % 32 or len(b) > 22*32: continue
    L.append('  {%d,%s,%du,%d},' % (len(b)//32, carr(b + bytes(22*32-len(b))), v['input']['index'], 1 if v['output'] else 0))
L.append('};')
open(out, 'w').write('\n'.join(L) + '\n')
print(len(rt), 'retarget', len(chainA), 'A', len(B['headers']), 'B', len(pr), 'proofs')
